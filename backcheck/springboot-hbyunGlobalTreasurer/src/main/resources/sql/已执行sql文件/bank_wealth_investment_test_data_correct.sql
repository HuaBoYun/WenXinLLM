    ACTUAL_RETURN AS "实际收益",
    INVESTMENT_TERM AS "投资期限(天)",
    VALUE_DATE AS "起息日",
    MATURITY_DATE AS "到期日",
    REDEMPTION_DATE AS "赎回日",
    RISK_LEVEL AS "风险等级",
    INVESTMENT_STATUS AS "投资状态",
    CURRENCY_CODE AS "币种"
