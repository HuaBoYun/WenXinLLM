-- 创建异常处理表
CREATE TABLE TBL_EXCEPTION_HANDLING (
    EXCEPTION_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    EXCEPTION_NO VARCHAR(50) NOT NULL,
    EXCEPTION_TYPE VARCHAR(50),
    EXCEPTION_LEVEL VARCHAR(20),
    SOURCE_TYPE VARCHAR(20),
    SOURCE_ID VARCHAR(64),
    SOURCE_NO VARCHAR(50),
    POOL_ID VARCHAR(64),
    COMPANY_ID VARCHAR(64),
    COMPANY_NAME VARCHAR(200),
    EXCEPTION_TITLE VARCHAR(200),
    EXCEPTION_DESC CLOB,
    EXCEPTION_TIME TIMESTAMP,
    EXCEPTION_STATUS VARCHAR(20),
    HANDLE_METHOD VARCHAR(20),
    HANDLE_TIME TIMESTAMP,
    HANDLE_BY VARCHAR(100),
    HANDLE_RESULT VARCHAR(500),
    RETRY_COUNT INTEGER DEFAULT 0,
    MAX_RETRY INTEGER DEFAULT 3,
    NEXT_RETRY_TIME TIMESTAMP,
    REMARK VARCHAR(1000),
    CREATE_BY VARCHAR(100),
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(100),
    UPDATE_TIME TIMESTAMP,
    DEL_FLAG VARCHAR(10) DEFAULT '0'
);

-- 创建索引
CREATE INDEX IDX_EXCEPTION_NO ON TBL_EXCEPTION_HANDLING(EXCEPTION_NO);
CREATE INDEX IDX_EXCEPTION_TYPE ON TBL_EXCEPTION_HANDLING(EXCEPTION_TYPE);
CREATE INDEX IDX_EXCEPTION_LEVEL ON TBL_EXCEPTION_HANDLING(EXCEPTION_LEVEL);
CREATE INDEX IDX_EXCEPTION_STATUS ON TBL_EXCEPTION_HANDLING(EXCEPTION_STATUS);
CREATE INDEX IDX_SOURCE_TYPE ON TBL_EXCEPTION_HANDLING(SOURCE_TYPE);
CREATE INDEX IDX_COMPANY_ID ON TBL_EXCEPTION_HANDLING(COMPANY_ID);
CREATE INDEX IDX_EXCEPTION_TIME ON TBL_EXCEPTION_HANDLING(EXCEPTION_TIME);
CREATE INDEX IDX_CREATE_TIME ON TBL_EXCEPTION_HANDLING(CREATE_TIME);

-- 添加表注释
COMMENT ON TABLE TBL_EXCEPTION_HANDLING IS '异常处理表';

