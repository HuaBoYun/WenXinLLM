-- =============================================
-- 说明
-- =============================================
-- 异常类型 (EXCEPTION_TYPE):
--   TRANSFER_FAILED - 转账失败
--   TIMEOUT - 超时
--   DATA_ERROR - 数据错误
--   SYSTEM_ERROR - 系统错误
--
-- 异常级别 (EXCEPTION_LEVEL):
--   NORMAL - 普通
--   IMPORTANT - 重要
--   URGENT - 紧急
--
-- 来源类型 (SOURCE_TYPE):
--   COLLECTION - 归集
--   ALLOCATION - 下拨
--   LOAN - 借贷
--
-- 异常状态 (EXCEPTION_STATUS):
--   PENDING - 待处理
--   HANDLING - 处理中
--   RESOLVED - 已解决
