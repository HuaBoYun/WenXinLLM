COMMENT ON COLUMN TC_SEAL_ARCHIVE_V2.IS_ACTIVE IS '是否启用:1启用,0禁用';
COMMENT ON COLUMN TC_SEAL_ARCHIVE_V2.VERSION_NO IS '版本号';
