-- ============================================
-- 1. 印鉴类型表
-- ============================================
CREATE TABLE IF NOT EXISTS TC_SEAL_TYPE (
    SEAL_ID VARCHAR2(50) NOT NULL,
    TYPE_CODE VARCHAR2(50) NOT NULL,
    TYPE_NAME VARCHAR2(100) NOT NULL,
    SORT_ORDER INTEGER DEFAULT 0,
    IS_ENABLED INTEGER DEFAULT 1,
    DESCRIPTION VARCHAR2(500),
    CREATE_BY VARCHAR2(50),
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR2(50),
    UPDATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    REMARK VARCHAR2(500),
    CONSTRAINT PK_TC_SEAL_TYPE PRIMARY KEY (SEAL_ID)
);

-- 评论
COMMENT ON TABLE TC_SEAL_TYPE IS '印鉴类型表';
COMMENT ON COLUMN TC_SEAL_TYPE.SEAL_ID IS '类型ID';
COMMENT ON COLUMN TC_SEAL_TYPE.TYPE_CODE IS '类型编码';
COMMENT ON COLUMN TC_SEAL_TYPE.TYPE_NAME IS '类型名称';
COMMENT ON COLUMN TC_SEAL_TYPE.SORT_ORDER IS '排序号';
COMMENT ON COLUMN TC_SEAL_TYPE.IS_ENABLED IS '是否启用:1启用,0禁用';
COMMENT ON COLUMN TC_SEAL_TYPE.DESCRIPTION IS '描述';
COMMENT ON COLUMN TC_SEAL_TYPE.CREATE_BY IS '创建人';
COMMENT ON COLUMN TC_SEAL_TYPE.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN TC_SEAL_TYPE.UPDATE_BY IS '更新人';
COMMENT ON COLUMN TC_SEAL_TYPE.UPDATE_TIME IS '更新时间';
COMMENT ON COLUMN TC_SEAL_TYPE.REMARK IS '备注';

-- 创建索引
CREATE INDEX IF NOT EXISTS IDX_SEAL_TYPE_CODE ON TC_SEAL_TYPE(TYPE_CODE);
CREATE INDEX IF NOT EXISTS IDX_SEAL_TYPE_ENABLED ON TC_SEAL_TYPE(IS_ENABLED);

