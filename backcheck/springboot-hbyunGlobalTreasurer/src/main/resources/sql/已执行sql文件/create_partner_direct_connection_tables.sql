    BANK_NAME VARCHAR(200) NOT NULL COMMENT '银行名称',
    ACCOUNT_ID BIGINT COMMENT '账户ID',
    ACCOUNT_NUMBER VARCHAR(100) COMMENT '账户号码',
    ACCOUNT_NAME VARCHAR(200) COMMENT '账户名称',
    CONTRACT_TYPE VARCHAR(50) NOT NULL COMMENT '合同类型',
    CONTRACT_STATUS VARCHAR(50) NOT NULL COMMENT '合同状态',
    APPLICATION_DATE DATE COMMENT '申请日期',
    APPLICANT_ID BIGINT COMMENT '申请人ID',
    APPLICANT_NAME VARCHAR(100) COMMENT '申请人姓名',
    APPLICANT_DEPARTMENT VARCHAR(200) COMMENT '申请部门',
    QUALIFICATION_VERIFICATION_STATUS VARCHAR(50) COMMENT '资质验证状态',
    QUALIFICATION_VERIFICATION_TIME TIMESTAMP COMMENT '资质验证时间',
    QUALIFICATION_VERIFIER_ID BIGINT COMMENT '资质验证人ID',
    QUALIFICATION_VERIFIER_NAME VARCHAR(100) COMMENT '资质验证人姓名',
    VERIFICATION_RESULT VARCHAR(1000) COMMENT '资质验证结果',
    AGREEMENT_SIGNING_STATUS VARCHAR(50) COMMENT '协议签署状态',
    AGREEMENT_SIGNING_TIME TIMESTAMP COMMENT '协议签署时间',
    AGREEMENT_SIGNER_ID BIGINT COMMENT '协议签署人ID',
    AGREEMENT_SIGNER_NAME VARCHAR(100) COMMENT '协议签署人姓名',
    ELECTRONIC_CONTRACT_PATH VARCHAR(1000) COMMENT '电子合同文件路径',
    PAPER_CONTRACT_PATH VARCHAR(1000) COMMENT '纸质合同文件路径',
    SERVICE_ACTIVATION_STATUS VARCHAR(50) COMMENT '服务激活状态',
    SERVICE_ACTIVATION_TIME TIMESTAMP COMMENT '服务激活时间',
    SERVICE_ACTIVATOR_ID BIGINT COMMENT '服务激活人ID',
    SERVICE_ACTIVATOR_NAME VARCHAR(100) COMMENT '服务激活人姓名',
    CONTRACT_EFFECTIVE_DATE DATE COMMENT '合同生效日期',
    CONTRACT_EXPIRE_DATE DATE COMMENT '合同到期日期',
    CONTRACT_TERM_MONTHS INTEGER COMMENT '合同期限（月）',
    AUTO_RENEWAL INTEGER DEFAULT 0 COMMENT '是否自动续签',
    RENEWAL_REMINDER_DAYS INTEGER DEFAULT 30 COMMENT '续约提醒天数',
    NEXT_RENEWAL_DATE DATE COMMENT '下次续签日期',
    RENEWAL_COUNT INTEGER DEFAULT 0 COMMENT '续签次数',
    MAX_RENEWAL_COUNT INTEGER DEFAULT 0 COMMENT '最大续签次数',
    TERMINATION_REASON VARCHAR(1000) COMMENT '终止原因',
    TERMINATION_DATE DATE COMMENT '终止日期',
    TERMINATOR_ID BIGINT COMMENT '终止人ID',
    TERMINATOR_NAME VARCHAR(100) COMMENT '终止人姓名',
    SERVICE_FEE DECIMAL(20,2) COMMENT '服务费用',
    FEE_PERIOD VARCHAR(50) COMMENT '费用周期',
    PAYMENT_METHOD VARCHAR(50) COMMENT '费用支付方式',
    SERVICE_LEVEL VARCHAR(50) COMMENT '服务等级',
    SLA_DOCUMENT_PATH VARCHAR(1000) COMMENT '服务水平协议文件路径',
    CONTACT_NAME VARCHAR(100) COMMENT '联系人姓名',
    CONTACT_PHONE VARCHAR(50) COMMENT '联系人电话',
    CONTACT_EMAIL VARCHAR(200) COMMENT '联系人邮箱',
    TECHNICAL_SUPPORT_CONTACT VARCHAR(500) COMMENT '技术支持联系方式',
    BUSINESS_SUPPORT_CONTACT VARCHAR(500) COMMENT '业务支持联系方式',
    AVAILABILITY_GUARANTEE DECIMAL(5,2) COMMENT '服务可用性保证（百分比）',
    RECOVERY_TIME_REQUIREMENT INTEGER COMMENT '故障恢复时间要求（小时）',
    SPECIAL_TERMS CLOB COMMENT '特殊条款',
    CONTRACT_NOTES CLOB COMMENT '合同备注',
    APPROVAL_STATUS VARCHAR(50) COMMENT '审批状态',
    APPROVER_ID BIGINT COMMENT '审批人ID',
    APPROVER_NAME VARCHAR(100) COMMENT '审批人姓名',
    APPROVAL_TIME TIMESTAMP COMMENT '审批时间',
    APPROVAL_COMMENTS CLOB COMMENT '审批意见',
    CONTRACT_DOCUMENT_PATH VARCHAR(1000) COMMENT '合同文件存储路径',
    ATTACHMENT_PATHS CLOB COMMENT '相关附件路径',
    ORG_ID BIGINT NOT NULL COMMENT '组织ID',
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    CREATE_USER BIGINT COMMENT '创建用户',
    UPDATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
    UPDATE_USER BIGINT COMMENT '更新用户',
    IS_ENABLED INTEGER DEFAULT 1 COMMENT '是否启用'
);

