-- 1. 银行接口配置表 (实体类 TreasuryBankInterfaceConfig 已存在，这里提供表结构参考)
CREATE TABLE IF NOT EXISTS TBL_TREASURY_BANK_INTERFACE_CONFIG (
    INTERFACE_CONFIG_ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    INTERFACE_CODE VARCHAR(100) NOT NULL COMMENT '接口编码',
    INTERFACE_NAME VARCHAR(200) NOT NULL COMMENT '接口名称',
    BANK_CODE VARCHAR(50) NOT NULL COMMENT '银行代码',
    BANK_NAME VARCHAR(200) NOT NULL COMMENT '银行名称',
    INTERFACE_TYPE VARCHAR(50) NOT NULL COMMENT '接口类型',
    PROTOCOL VARCHAR(20) NOT NULL COMMENT '接口协议',
    INTERFACE_VERSION VARCHAR(20) COMMENT '接口版本',
    REQUEST_METHOD VARCHAR(10) COMMENT '请求方法',
    SERVICE_URL VARCHAR(500) NOT NULL COMMENT '服务地址',
    SERVICE_PORT INTEGER COMMENT '服务端口',
    INTERFACE_PATH VARCHAR(500) COMMENT '接口路径',
    FULL_URL VARCHAR(1000) COMMENT '完整接口地址',
    REQUEST_HEADERS CLOB COMMENT '请求头（JSON格式）',
    REQUEST_TEMPLATE CLOB COMMENT '请求参数模板',
    RESPONSE_PARSE_RULE CLOB COMMENT '响应解析规则',
    AUTH_TYPE VARCHAR(50) NOT NULL COMMENT '认证方式',
    USERNAME VARCHAR(100) COMMENT '用户名',
    PASSWORD VARCHAR(500) COMMENT '密码',
    API_KEY VARCHAR(500) COMMENT 'API密钥',
    ACCESS_TOKEN VARCHAR(1000) COMMENT '访问令牌',
    TOKEN_TYPE VARCHAR(20) COMMENT '令牌类型',
    SIGN_ALGORITHM VARCHAR(20) COMMENT '签名算法',
    SIGN_SECRET VARCHAR(500) COMMENT '签名密钥',
    TIMESTAMP_FIELD VARCHAR(50) COMMENT '时间戳字段名',
    NONCE_FIELD VARCHAR(50) COMMENT '随机数字段名',
    CERT_PATH VARCHAR(500) COMMENT '证书路径',
    CERT_PASSWORD VARCHAR(200) COMMENT '证书密码',
    PUBLIC_KEY CLOB COMMENT '公钥',
    PRIVATE_KEY CLOB COMMENT '私钥',
    ENCRYPT_ALGORITHM VARCHAR(20) COMMENT '加密算法',
    ENCRYPT_KEY VARCHAR(500) COMMENT '加密密钥',
    ENCODING VARCHAR(20) DEFAULT 'UTF-8' COMMENT '编码格式',
    CONTENT_TYPE VARCHAR(100) DEFAULT 'application/json' COMMENT '内容类型',
    TIMEOUT_SECONDS INTEGER DEFAULT 30 COMMENT '超时时间（秒）',
    CONNECT_TIMEOUT INTEGER COMMENT '连接超时（秒）',
    READ_TIMEOUT INTEGER COMMENT '读取超时（秒）',
    RETRY_TIMES INTEGER DEFAULT 3 COMMENT '重试次数',
    RETRY_INTERVAL INTEGER DEFAULT 1000 COMMENT '重试间隔（毫秒）',
    CONNECTION_POOL_SIZE INTEGER COMMENT '连接池大小',
    MAX_CONNECTIONS INTEGER COMMENT '最大连接数',
    ENABLE_CONNECTION_POOL INTEGER DEFAULT 0 COMMENT '是否启用连接池',
    ENABLE_COMPRESSION INTEGER DEFAULT 0 COMMENT '是否启用压缩',
    VERIFY_SSL INTEGER DEFAULT 1 COMMENT '是否验证SSL证书',
    ENABLE_PROXY INTEGER DEFAULT 0 COMMENT '是否启用代理',
    PROXY_HOST VARCHAR(200) COMMENT '代理服务器地址',
    PROXY_PORT INTEGER COMMENT '代理服务器端口',
    PROXY_USERNAME VARCHAR(100) COMMENT '代理用户名',
    PROXY_PASSWORD VARCHAR(200) COMMENT '代理密码',
    SUPPORTED_BUSINESS_TYPES VARCHAR(500) COMMENT '支持的业务类型',
    INTERFACE_STATUS VARCHAR(20) DEFAULT 'ACTIVE' COMMENT '接口状态',
    MONITOR_LEVEL VARCHAR(20) COMMENT '监控等级',
    DESCRIPTION CLOB COMMENT '接口描述',
    TEST_STATUS VARCHAR(20) COMMENT '测试状态',
    LAST_TEST_TIME TIMESTAMP COMMENT '最后测试时间',
    LAST_TEST_RESULT VARCHAR(1000) COMMENT '最后测试结果',
    DOCUMENT_URL VARCHAR(500) COMMENT '接口文档URL',
    CATEGORY VARCHAR(100) COMMENT '接口分类',
    TAGS VARCHAR(500) COMMENT '标签',
    ORG_ID BIGINT NOT NULL COMMENT '组织ID',
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    CREATE_USER BIGINT COMMENT '创建用户',
    UPDATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
    UPDATE_USER BIGINT COMMENT '更新用户',
    IS_ENABLED INTEGER DEFAULT 1 COMMENT '是否启用'
);

-- 创建索引
CREATE INDEX IDX_BANK_INTERFACE_CODE ON TBL_TREASURY_BANK_INTERFACE_CONFIG(INTERFACE_CODE);
CREATE INDEX IDX_BANK_INTERFACE_BANK_CODE ON TBL_TREASURY_BANK_INTERFACE_CONFIG(BANK_CODE);
CREATE INDEX IDX_BANK_INTERFACE_TYPE ON TBL_TREASURY_BANK_INTERFACE_CONFIG(INTERFACE_TYPE);
CREATE INDEX IDX_BANK_INTERFACE_STATUS ON TBL_TREASURY_BANK_INTERFACE_CONFIG(INTERFACE_STATUS);
CREATE INDEX IDX_BANK_INTERFACE_ORG_ID ON TBL_TREASURY_BANK_INTERFACE_CONFIG(ORG_ID);
CREATE UNIQUE INDEX UNQ_BANK_INTERFACE_CODE_ORG ON TBL_TREASURY_BANK_INTERFACE_CONFIG(INTERFACE_CODE, ORG_ID) WHERE IS_DELETED = 0;

-- 2. 云连接合同表 (实体类 TreasuryCloudConnectionContract 已存在，这里提供表结构参考)
