-- 5. 银行接口测试记录表
CREATE TABLE IF NOT EXISTS TBL_BANK_INTERFACE_TEST_LOG (
    TEST_LOG_ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    INTERFACE_CONFIG_ID BIGINT NOT NULL COMMENT '接口配置ID',
    TEST_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '测试时间',
    TEST_RESULT VARCHAR(20) NOT NULL COMMENT '测试结果：SUCCESS-成功，FAILED-失败',
    RESPONSE_TIME INTEGER COMMENT '响应时间（毫秒）',
    ERROR_CODE VARCHAR(100) COMMENT '错误代码',
    ERROR_MESSAGE VARCHAR(2000) COMMENT '错误信息',
    TEST_DATA CLOB COMMENT '测试数据',
    RESPONSE_DATA CLOB COMMENT '响应数据',
    TEST_USER_ID BIGINT COMMENT '测试用户ID',
    TEST_USER_NAME VARCHAR(100) COMMENT '测试用户姓名',
    REMARK VARCHAR(1000) COMMENT '备注',
    ORG_ID BIGINT NOT NULL COMMENT '组织ID'
);

-- 创建索引
CREATE INDEX IDX_BANK_TEST_INTERFACE_ID ON TBL_BANK_INTERFACE_TEST_LOG(INTERFACE_CONFIG_ID);
CREATE INDEX IDX_BANK_TEST_TIME ON TBL_BANK_INTERFACE_TEST_LOG(TEST_TIME);
CREATE INDEX IDX_BANK_TEST_RESULT ON TBL_BANK_INTERFACE_TEST_LOG(TEST_RESULT);
CREATE INDEX IDX_BANK_TEST_ORG_ID ON TBL_BANK_INTERFACE_TEST_LOG(ORG_ID);

-- 6. 合同履约记录表
CREATE TABLE IF NOT EXISTS TBL_CONTRACT_PERFORMANCE_RECORD (
    PERFORMANCE_ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    CONTRACT_ID BIGINT NOT NULL COMMENT '合同ID',
    RECORD_DATE DATE NOT NULL COMMENT '记录日期',
    PERFORMANCE_TYPE VARCHAR(50) NOT NULL COMMENT '履约类型',
    PERFORMANCE_STATUS VARCHAR(20) NOT NULL COMMENT '履约状态',
    SERVICE_AVAILABILITY DECIMAL(5,2) COMMENT '服务可用性（百分比）',
    RESPONSE_TIME AVG COMMENT '平均响应时间（毫秒）',
    SERVICE_QUALITY_SCORE DECIMAL(5,2) COMMENT '服务质量评分',
    ISSUE_COUNT INTEGER DEFAULT 0 COMMENT '问题数量',
    RESOLVED_ISSUE_COUNT INTEGER DEFAULT 0 COMMENT '已解决问题数量',
    PENDING_ISSUE_COUNT INTEGER DEFAULT 0 COMMENT '待解决问题数量',
    DETAILED_REPORT CLOB COMMENT '详细报告',
    ATTACHMENT_PATHS VARCHAR(2000) COMMENT '附件路径',
    RECORD_USER_ID BIGINT COMMENT '记录用户ID',
    RECORD_USER_NAME VARCHAR(100) COMMENT '记录用户姓名',
    REMARK VARCHAR(1000) COMMENT '备注',
    ORG_ID BIGINT NOT NULL COMMENT '组织ID',
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间'
);

-- 创建索引
CREATE INDEX IDX_CONTRACT_PERFORMANCE_CONTRACT_ID ON TBL_CONTRACT_PERFORMANCE_RECORD(CONTRACT_ID);
CREATE INDEX IDX_CONTRACT_PERFORMANCE_DATE ON TBL_CONTRACT_PERFORMANCE_RECORD(RECORD_DATE);
CREATE INDEX IDX_CONTRACT_PERFORMANCE_TYPE ON TBL_CONTRACT_PERFORMANCE_RECORD(PERFORMANCE_TYPE);
CREATE INDEX IDX_CONTRACT_PERFORMANCE_ORG_ID ON TBL_CONTRACT_PERFORMANCE_RECORD(ORG_ID);

