    CONTRACT_ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    CONTRACT_NO VARCHAR(100) NOT NULL COMMENT '合同编号',
    CONTRACT_NAME VARCHAR(500) NOT NULL COMMENT '合同名称',
