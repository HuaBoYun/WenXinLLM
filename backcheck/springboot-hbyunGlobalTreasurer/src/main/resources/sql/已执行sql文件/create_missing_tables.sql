CREATE TABLE TBL_COMMERCIAL_BILL (
    BILL_ID BIGINT PRIMARY KEY,
    BILL_NO VARCHAR(50) NOT NULL UNIQUE,
    BILL_TYPE VARCHAR(20) NOT NULL,
    BILL_STATUS VARCHAR(20) DEFAULT 'NORMAL',
