    DRAWER_ACCOUNT VARCHAR(50),
    DRAWER_BANK VARCHAR(100),
    PAYEE_NAME VARCHAR(100),
    PAYEE_ACCOUNT VARCHAR(50),
    PAYEE_BANK VARCHAR(100),
    ACCEPTOR_NAME VARCHAR(100),
    ACCEPTOR_ACCOUNT VARCHAR(50),
    ACCEPTOR_BANK VARCHAR(100),
    ISSUE_LOCATION VARCHAR(100),
    GUARANTOR VARCHAR(100),
    REMARK VARCHAR(500),
    DELETE_FLAG INTEGER DEFAULT 0,
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATOR VARCHAR(50),
    UPDATER VARCHAR(50)
