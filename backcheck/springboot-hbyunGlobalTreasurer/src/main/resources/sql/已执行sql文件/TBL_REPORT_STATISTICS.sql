-- 说明
-- =============================================
-- 报表类型 (REPORT_TYPE):
--   COLLECTION - 归集报表
--   ALLOCATION - 下拨报表
--   LOAN - 借贷报表
--   COMPREHENSIVE - 综合报表
--
-- 报表周期 (REPORT_PERIOD):
--   DAILY - 日报
--   WEEKLY - 周报
--   MONTHLY - 月报
--   QUARTERLY - 季报
--   YEARLY - 年报
--
-- 报表状态 (REPORT_STATUS):
--   DRAFT - 草稿
--   GENERATED - 已生成
--   PUBLISHED - 已发布
--
-- 删除标志 (DEL_FLAG):
--   '0' - 正常
--   '1' - 已删除
