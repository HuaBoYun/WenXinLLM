-- 删除已存在的表（如果需要）
-- DROP TABLE IF EXISTS TBL_REPORT_STATISTICS;

-- 创建报表统计表
CREATE TABLE TBL_REPORT_STATISTICS (
    REPORT_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    REPORT_NO VARCHAR(50) NOT NULL,
    REPORT_NAME VARCHAR(200) NOT NULL,
    REPORT_TYPE VARCHAR(20),
    REPORT_PERIOD VARCHAR(20),
    POOL_ID VARCHAR(64),
    COMPANY_ID VARCHAR(64),
    COMPANY_NAME VARCHAR(200),
    START_DATE TIMESTAMP,
    END_DATE TIMESTAMP,
    TOTAL_COLLECTION DECIMAL(20,2),
    TOTAL_ALLOCATION DECIMAL(20,2),
    TOTAL_LOAN DECIMAL(20,2),
    TOTAL_REPAYMENT DECIMAL(20,2),
    TOTAL_INTEREST DECIMAL(20,2),
    COLLECTION_COUNT INTEGER,
    ALLOCATION_COUNT INTEGER,
    LOAN_COUNT INTEGER,
    SUCCESS_RATE DECIMAL(5,4),
    AVERAGE_AMOUNT DECIMAL(20,2),
    REPORT_STATUS VARCHAR(20),
    GENERATE_TIME TIMESTAMP,
    GENERATE_BY VARCHAR(100),
    REPORT_DATA CLOB,
    REMARK VARCHAR(1000),
    CREATE_BY VARCHAR(100),
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(100),
    UPDATE_TIME TIMESTAMP,
    DEL_FLAG VARCHAR(10) DEFAULT '0'
);

-- 创建索引
CREATE INDEX IDX_REPORT_NO ON TBL_REPORT_STATISTICS(REPORT_NO);
CREATE INDEX IDX_REPORT_TYPE ON TBL_REPORT_STATISTICS(REPORT_TYPE);
CREATE INDEX IDX_REPORT_PERIOD ON TBL_REPORT_STATISTICS(REPORT_PERIOD);
CREATE INDEX IDX_COMPANY_ID ON TBL_REPORT_STATISTICS(COMPANY_ID);
CREATE INDEX IDX_GENERATE_TIME ON TBL_REPORT_STATISTICS(GENERATE_TIME);

-- 添加表注释
COMMENT ON TABLE TBL_REPORT_STATISTICS IS '报表统计表';

