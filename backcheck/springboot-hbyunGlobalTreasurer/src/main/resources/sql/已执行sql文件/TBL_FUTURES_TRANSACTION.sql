-- 删除表(如果存在)
DROP TABLE IF EXISTS TBL_FUTURES_TRANSACTION;

-- 创建期货交易表
CREATE TABLE TBL_FUTURES_TRANSACTION (
    TRANSACTION_ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    CONTRACT_CODE VARCHAR(50) NOT NULL,
    FUTURES_TYPE VARCHAR(50) NOT NULL,
    UNDERLYING_ASSET VARCHAR(100) NOT NULL,
    DIRECTION VARCHAR(10) NOT NULL,
    CONTRACT_SIZE DECIMAL(20, 4) NOT NULL,
    OPEN_PRICE DECIMAL(20, 6) NOT NULL,
    CURRENT_PRICE DECIMAL(20, 6),
    CURRENCY VARCHAR(10) NOT NULL,
    TRADE_DATE DATE NOT NULL,
    EXPIRY_DATE DATE NOT NULL,
    INITIAL_MARGIN DECIMAL(20, 4),
    MAINTENANCE_MARGIN DECIMAL(20, 4),
    MARGIN_RATIO DECIMAL(10, 6),
    MARGIN DECIMAL(20, 4),
    UNREALIZED_PNL DECIMAL(20, 4),
    REALIZED_PNL DECIMAL(20, 4),
    "EXCHANGE" VARCHAR(50),
    BROKER VARCHAR(200),
    TRADER VARCHAR(50),
    STATUS VARCHAR(20) DEFAULT 'PENDING',
    REMARK VARCHAR(500),
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATE_BY VARCHAR(100),
    UPDATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(100),
    DEL_FLAG VARCHAR(1) DEFAULT '0',
    ORG_ID BIGINT NOT NULL
);

-- 添加注释
COMMENT ON TABLE TBL_FUTURES_TRANSACTION IS '期货交易表';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.TRANSACTION_ID IS '主键ID';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.CONTRACT_CODE IS '合约编号';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.FUTURES_TYPE IS '期货类型(COMMODITY-商品期货, FINANCIAL-金融期货, INDEX-股指期货, FX-外汇期货)';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.UNDERLYING_ASSET IS '标的资产';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.DIRECTION IS '交易方向(LONG-多头, SHORT-空头)';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.CONTRACT_SIZE IS '合约数量';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.OPEN_PRICE IS '开仓价格';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.CURRENT_PRICE IS '当前价格';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.CURRENCY IS '币种';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.TRADE_DATE IS '交易日期';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.EXPIRY_DATE IS '到期日期';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.INITIAL_MARGIN IS '初始保证金';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.MAINTENANCE_MARGIN IS '维持保证金';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.MARGIN_RATIO IS '保证金比例';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.MARGIN IS '保证金余额';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.UNREALIZED_PNL IS '浮动盈亏';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.REALIZED_PNL IS '已实现盈亏';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION."EXCHANGE" IS '交易所(SHFE-上期所, DCE-大商所, CZCE-郑商所, CFFEX-中金所, INE-能源中心)';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.BROKER IS '期货公司';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.TRADER IS '交易员';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.STATUS IS '状态(PENDING-待生效, OPEN-持仓中, CLOSED-已平仓, SETTLED-已交割, CANCELLED-已取消)';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.REMARK IS '备注';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.CREATE_BY IS '创建人';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.UPDATE_TIME IS '更新时间';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.UPDATE_BY IS '更新人';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.DEL_FLAG IS '删除标志(0-正常, 1-删除)';
COMMENT ON COLUMN TBL_FUTURES_TRANSACTION.ORG_ID IS '机构ID';

-- 创建索引
CREATE INDEX IDX_FUTURES_CONTRACT_CODE ON TBL_FUTURES_TRANSACTION(CONTRACT_CODE);
CREATE INDEX IDX_FUTURES_TYPE ON TBL_FUTURES_TRANSACTION(FUTURES_TYPE);
CREATE INDEX IDX_FUTURES_STATUS ON TBL_FUTURES_TRANSACTION(STATUS);
CREATE INDEX IDX_FUTURES_CURRENCY ON TBL_FUTURES_TRANSACTION(CURRENCY);
CREATE INDEX IDX_FUTURES_EXCHANGE ON TBL_FUTURES_TRANSACTION("EXCHANGE");
CREATE INDEX IDX_FUTURES_EXPIRY_DATE ON TBL_FUTURES_TRANSACTION(EXPIRY_DATE);
CREATE INDEX IDX_FUTURES_CREATE_TIME ON TBL_FUTURES_TRANSACTION(CREATE_TIME);

