    PRODUCT_NAME AS "产品名称",
    PRODUCT_TYPE AS "产品类型",
    ISSUER AS "发行机构",
    RISK_LEVEL AS "风险等级",
    EXPECTED_RETURN_RATE AS "预期收益率",
    MIN_INVESTMENT_AMOUNT AS "最小投资金额",
    MAX_INVESTMENT_AMOUNT AS "最大投资金额",
    INVESTMENT_TERM AS "投资期限(天)",
    NET_VALUE AS "净值",
    PRODUCT_STATUS AS "产品状态",
    LAUNCH_DATE AS "发行日期",
    MATURITY_DATE AS "到期日期"
FROM TBL_INVESTMENT_PRODUCT
WHERE DELETE_FLAG = 0
ORDER BY CREATED_TIME DESC;
