-- 删除表(如果存在)
DROP TABLE IF EXISTS TBL_FORWARD_TRANSACTION;

-- 创建远期交易表
CREATE TABLE TBL_FORWARD_TRANSACTION (
    TRANSACTION_ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    CONTRACT_CODE VARCHAR(50) NOT NULL,
    TRANSACTION_TYPE VARCHAR(50) NOT NULL,
    UNDERLYING_ASSET VARCHAR(100) NOT NULL,
    CONTRACT_SIZE DECIMAL(20, 4) NOT NULL,
    FORWARD_RATE DECIMAL(20, 8) NOT NULL,
    SPOT_RATE DECIMAL(20, 8),
    CURRENT_VALUE DECIMAL(20, 4),
    PNL DECIMAL(20, 4),
    CURRENCY VARCHAR(10) NOT NULL,
    TRADE_DATE DATE NOT NULL,
    MATURITY_DATE DATE NOT NULL,
    DELIVERY_DATE DATE,
    DELIVERY_PRICE DECIMAL(20, 8),
    SETTLEMENT_TYPE VARCHAR(50),
    COUNTERPARTY VARCHAR(200),
    COUNTERPARTY_RATING VARCHAR(20),
    PURPOSE VARCHAR(500),
    STATUS VARCHAR(20) DEFAULT 'PENDING',
    REMARK VARCHAR(1000),
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATE_BY VARCHAR(100),
    UPDATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(100),
    DEL_FLAG VARCHAR(1) DEFAULT '0',
    ORG_ID BIGINT NOT NULL
);

-- 添加注释
COMMENT ON TABLE TBL_FORWARD_TRANSACTION IS '远期交易表';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.TRANSACTION_ID IS '主键ID';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.CONTRACT_CODE IS '合约编号';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.TRANSACTION_TYPE IS '交易类型(FX-外汇远期, INTEREST_RATE-利率远期, COMMODITY-商品远期)';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.UNDERLYING_ASSET IS '标的资产';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.CONTRACT_SIZE IS '合约数量(名义本金)';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.FORWARD_RATE IS '远期汇率/利率';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.SPOT_RATE IS '即期汇率/利率';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.CURRENT_VALUE IS '当前估值';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.PNL IS '损益';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.CURRENCY IS '币种';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.TRADE_DATE IS '交易日期';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.MATURITY_DATE IS '到期日期';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.DELIVERY_DATE IS '交割日期';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.DELIVERY_PRICE IS '交割价格';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.SETTLEMENT_TYPE IS '结算类型(CASH-现金结算, PHYSICAL-实物交割)';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.COUNTERPARTY IS '交易对手';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.COUNTERPARTY_RATING IS '对手评级';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.PURPOSE IS '交易目的(HEDGE-套期保值, SPECULATION-投机, ARBITRAGE-套利)';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.STATUS IS '状态(PENDING-待生效, ACTIVE-生效中, SETTLED-已交割, CANCELLED-已取消)';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.REMARK IS '备注';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.CREATE_BY IS '创建人';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.UPDATE_TIME IS '更新时间';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.UPDATE_BY IS '更新人';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.DEL_FLAG IS '删除标志(0-正常, 1-删除)';
COMMENT ON COLUMN TBL_FORWARD_TRANSACTION.ORG_ID IS '机构ID';

-- 创建索引
CREATE INDEX IDX_FORWARD_CONTRACT_CODE ON TBL_FORWARD_TRANSACTION(CONTRACT_CODE);
CREATE INDEX IDX_FORWARD_TYPE ON TBL_FORWARD_TRANSACTION(TRANSACTION_TYPE);
CREATE INDEX IDX_FORWARD_STATUS ON TBL_FORWARD_TRANSACTION(STATUS);
CREATE INDEX IDX_FORWARD_CURRENCY ON TBL_FORWARD_TRANSACTION(CURRENCY);
CREATE INDEX IDX_FORWARD_MATURITY_DATE ON TBL_FORWARD_TRANSACTION(MATURITY_DATE);
CREATE INDEX IDX_FORWARD_CREATE_TIME ON TBL_FORWARD_TRANSACTION(CREATE_TIME);

