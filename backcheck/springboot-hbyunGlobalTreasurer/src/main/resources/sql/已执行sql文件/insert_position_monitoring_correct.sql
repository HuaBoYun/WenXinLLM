-- 查询所有ACTIVE和PENDING状态的衍生品持仓(用于前端显示)
SELECT 'TOTAL_POSITIONS: ' || COUNT(*) AS TOTAL_RECORDS FROM (
    SELECT 'FORWARD' AS PRODUCT_TYPE, "CONTRACT_CODE", "UNDERLYING_ASSET", "NOTIONAL_AMOUNT" AS POSITION_SIZE,
           "CURRENT_VALUE" AS MARKET_VALUE, "PNL" AS UNREALIZED_PNL", NULL AS DELTA, NULL AS GAMMA,
           "MATURITY_DATE", "RISK_LIMIT"
    FROM "REDACTED"."TBL_FORWARD_TRANSACTION"
    WHERE "DEL_FLAG" = '0' AND "STATUS" IN ('ACTIVE', 'PENDING') AND "ORG_ID" = 1

    UNION ALL

    SELECT 'OPTION', "CONTRACT_CODE", "UNDERLYING_ASSET", "CONTRACT_SIZE",
           "THEORETICAL_VALUE", "THEORETICAL_VALUE" - "PREMIUM", "DELTA", "GAMMA",
           "EXPIRY_DATE", NULL
    FROM "REDACTED"."TBL_OPTION_TRANSACTION"
    WHERE "DEL_FLAG" = '0' AND "STATUS" IN ('ACTIVE', 'PENDING') AND "ORG_ID" = 1

    UNION ALL

    SELECT 'FUTURES', "CONTRACT_CODE", "UNDERLYING_ASSET", "CONTRACT_SIZE",
           "CONTRACT_SIZE" * "CURRENT_PRICE", "UNREALIZED_PNL", NULL, NULL,
           "EXPIRY_DATE", NULL
    FROM "REDACTED"."TBL_FUTURES_TRANSACTION"
    WHERE "DEL_FLAG" = '0' AND "STATUS" IN ('ACTIVE', 'PENDING') AND "ORG_ID" = 1

    UNION ALL

    SELECT 'SWAP', "CONTRACT_CODE", "UNDERLYING_ASSET", "NOTIONAL_AMOUNT",
           "CURRENT_VALUE", "CURRENT_VALUE", NULL, NULL,
           "MATURITY_DATE", NULL
    FROM "REDACTED"."TBL_SWAP_TRANSACTION"
    WHERE "DEL_FLAG" = '0' AND "STATUS" IN ('ACTIVE', 'PENDING') AND "ORG_ID" = 1
) AS ALL_POSITIONS;
