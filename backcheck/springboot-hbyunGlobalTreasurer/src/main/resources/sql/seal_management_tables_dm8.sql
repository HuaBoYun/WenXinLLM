CREATE INDEX IDX_SEAL_COMB_BTYPE ON TBL_SEAL_COMBINATION(BUSINESS_TYPE);
CREATE INDEX IDX_SEAL_COMB_ORG ON TBL_SEAL_COMBINATION(ORG_ID);

