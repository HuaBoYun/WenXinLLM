-- =====================================================

-- 创建表
CREATE TABLE TBL_SEAL_COMBINATION (
    COMBINATION_ID VARCHAR(32) NOT NULL PRIMARY KEY,
    COMBINATION_CODE VARCHAR(50) NOT NULL UNIQUE,
    COMBINATION_NAME VARCHAR(100) NOT NULL,
    COMBINATION_TYPE VARCHAR(20) NOT NULL,
    BUSINESS_TYPE VARCHAR(50),
    AUTHORITY_LEVEL VARCHAR(20),
    MAX_AMOUNT_LIMIT DECIMAL(18,2),
    USAGE_COUNT INTEGER DEFAULT 0,
    IS_ENABLED INTEGER DEFAULT 1,
    DESCRIPTION VARCHAR(500),
    ORG_ID VARCHAR(32),
    CREATE_TIME TIMESTAMP DEFAULT SYSDATE,
    UPDATE_TIME TIMESTAMP DEFAULT SYSDATE,
    CREATE_USER VARCHAR(50),
    UPDATE_USER VARCHAR(50)
);

-- 表注释
COMMENT ON TABLE TBL_SEAL_COMBINATION IS '印鉴组合配置表';

-- 字段注释
COMMENT ON COLUMN TBL_SEAL_COMBINATION.COMBINATION_ID IS '组合ID(主键)';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.COMBINATION_CODE IS '组合编码(唯一)';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.COMBINATION_NAME IS '组合名称';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.COMBINATION_TYPE IS '组合类型(SINGLE_SEAL-单印章,DUAL_SEAL-双印章,MULTI_SEAL-多印章)';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.BUSINESS_TYPE IS '业务类型(FUND_TRANSFER-资金划转,INVESTMENT_TRANSACTION-投资交易,CONTRACT_SIGNING-合同签署)';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.AUTHORITY_LEVEL IS '权限级别(LEVEL_1-一级,LEVEL_2-二级,LEVEL_3-三级)';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.MAX_AMOUNT_LIMIT IS '最大金额限制';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.USAGE_COUNT IS '使用次数';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.IS_ENABLED IS '是否启用(1-启用,0-禁用)';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.DESCRIPTION IS '描述';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.ORG_ID IS '组织ID';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.UPDATE_TIME IS '更新时间';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.CREATE_USER IS '创建用户';
COMMENT ON COLUMN TBL_SEAL_COMBINATION.UPDATE_USER IS '更新用户';

-- 创建索引
CREATE INDEX IDX_SEAL_COMB_CODE ON TBL_SEAL_COMBINATION(COMBINATION_CODE);
