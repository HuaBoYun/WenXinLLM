-- 表5: 票据池表
DROP TABLE IF EXISTS TBL_BILL_POOL;

CREATE TABLE TBL_BILL_POOL (
    POOL_ID DECIMAL(20,0) PRIMARY KEY,
    POOL_NAME VARCHAR(200) NOT NULL,
    POOL_NO VARCHAR(50) NOT NULL,
    POOL_TYPE VARCHAR(20),
    POOL_STATUS VARCHAR(20),
    TOTAL_AMOUNT DECIMAL(18,2) DEFAULT 0,
    BILL_COUNT INTEGER DEFAULT 0,
    AVAILABLE_AMOUNT DECIMAL(18,2) DEFAULT 0,
    PLEDGED_AMOUNT DECIMAL(18,2) DEFAULT 0,
    CREATOR_ID DECIMAL(20,0),
    CREATOR_NAME VARCHAR(100),
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP,
    CREATE_USER VARCHAR(50),
    UPDATE_USER VARCHAR(50),
    REMARK VARCHAR(500)
);

COMMENT ON TABLE TBL_BILL_POOL IS '票据池表';
COMMENT ON COLUMN TBL_BILL_POOL.POOL_ID IS '票据池ID';
COMMENT ON COLUMN TBL_BILL_POOL.POOL_NAME IS '票据池名称';
COMMENT ON COLUMN TBL_BILL_POOL.POOL_NO IS '票据池编号';
COMMENT ON COLUMN TBL_BILL_POOL.POOL_TYPE IS '票据池类型(自营/代持/质押)';
COMMENT ON COLUMN TBL_BILL_POOL.POOL_STATUS IS '票据池状态(正常/冻结/关闭)';
COMMENT ON COLUMN TBL_BILL_POOL.TOTAL_AMOUNT IS '总金额';
COMMENT ON COLUMN TBL_BILL_POOL.BILL_COUNT IS '票据数量';
COMMENT ON COLUMN TBL_BILL_POOL.AVAILABLE_AMOUNT IS '可用金额';
COMMENT ON COLUMN TBL_BILL_POOL.PLEDGED_AMOUNT IS '已质押金额';

CREATE INDEX IDX_POOL_NO ON TBL_BILL_POOL(POOL_NO);
CREATE INDEX IDX_POOL_STATUS ON TBL_BILL_POOL(POOL_STATUS);

-- 票据池关联表
DROP TABLE IF EXISTS TBL_BILL_POOL_ITEM;

CREATE TABLE TBL_BILL_POOL_ITEM (
    ITEM_ID DECIMAL(20,0) PRIMARY KEY,
    POOL_ID DECIMAL(20,0),
    BILL_ID DECIMAL(20,0),
    ADD_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    REMOVE_TIME TIMESTAMP,
    STATUS VARCHAR(20),
    CREATE_USER VARCHAR(50)
