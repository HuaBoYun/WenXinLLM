-- 表8: 票据风险评估表
DROP TABLE IF EXISTS TBL_BILL_RISK_ASSESSMENT;

CREATE TABLE TBL_BILL_RISK_ASSESSMENT (
    RISK_ID DECIMAL(20,0) PRIMARY KEY,
    BILL_ID DECIMAL(20,0),
    ASSESSMENT_NO VARCHAR(50) NOT NULL,
    RISK_LEVEL VARCHAR(20),
    RISK_TYPE VARCHAR(20),
    RISK_SCORE INTEGER,
    ASSESSMENT_STATUS VARCHAR(20),
    ASSESSMENT_DATE TIMESTAMP,
    ASSESSOR VARCHAR(100),
    RISK_DESC VARCHAR(1000),
    SUGGESTION VARCHAR(1000),
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP,
    CREATE_USER VARCHAR(50),
    UPDATE_USER VARCHAR(50),
    REMARK VARCHAR(500)
);

COMMENT ON TABLE TBL_BILL_RISK_ASSESSMENT IS '票据风险评估表';
COMMENT ON COLUMN TBL_BILL_RISK_ASSESSMENT.RISK_ID IS '风险评估ID';
COMMENT ON COLUMN TBL_BILL_RISK_ASSESSMENT.BILL_ID IS '票据ID';
COMMENT ON COLUMN TBL_BILL_RISK_ASSESSMENT.ASSESSMENT_NO IS '评估编号';
COMMENT ON COLUMN TBL_BILL_RISK_ASSESSMENT.RISK_LEVEL IS '风险等级(低/中/高)';
COMMENT ON COLUMN TBL_BILL_RISK_ASSESSMENT.RISK_TYPE IS '风险类型(信用风险/市场风险/操作风险)';
COMMENT ON COLUMN TBL_BILL_RISK_ASSESSMENT.RISK_SCORE IS '风险评分';
COMMENT ON COLUMN TBL_BILL_RISK_ASSESSMENT.ASSESSMENT_STATUS IS '评估状态(草稿/已完成)';

CREATE INDEX IDX_ASSESSMENT_NO ON TBL_BILL_RISK_ASSESSMENT(ASSESSMENT_NO);
CREATE INDEX IDX_RISK_LEVEL ON TBL_BILL_RISK_ASSESSMENT(RISK_LEVEL);

COMMIT;

