    SIGN_TIME TIMESTAMP,
    VERIFICATION_TIME TIMESTAMP,
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP,
    CREATE_USER VARCHAR(50),
    UPDATE_USER VARCHAR(50),
    REMARK VARCHAR(500)
);

COMMENT ON TABLE TBL_ELECTRONIC_BILL IS '电子票据表';
COMMENT ON COLUMN TBL_ELECTRONIC_BILL.E_BILL_ID IS '电子票据ID';
COMMENT ON COLUMN TBL_ELECTRONIC_BILL.E_BILL_NO IS '电子票据号码';
