-- 表1: 票据信息表
DROP TABLE IF EXISTS TBL_BILL_INSTRUMENT;

CREATE TABLE TBL_BILL_INSTRUMENT (
    INSTRUMENT_ID DECIMAL(20,0) PRIMARY KEY,
    INSTRUMENT_NO VARCHAR(50) NOT NULL,
    BILL_NO VARCHAR(50),
    BILL_TYPE VARCHAR(20),
    BILL_AMOUNT DECIMAL(18,2),
    CURRENCY_CODE VARCHAR(10) DEFAULT 'CNY',
    DRAWER VARCHAR(200),
    DRAWER_ACCOUNT VARCHAR(100),
    PAYEE VARCHAR(200),
    PAYEE_ACCOUNT VARCHAR(100),
    ACCEPTOR VARCHAR(200),
    ACCEPTOR_ACCOUNT VARCHAR(100),
    ISSUE_DATE TIMESTAMP,
    MATURITY_DATE TIMESTAMP,
    BILL_STATUS VARCHAR(20),
    DELETE_FLAG DECIMAL(1) DEFAULT 0,
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP,
    CREATE_USER VARCHAR(50),
    UPDATE_USER VARCHAR(50),
    REMARK VARCHAR(500)
);

COMMENT ON TABLE TBL_BILL_INSTRUMENT IS '票据信息表';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.INSTRUMENT_ID IS '票据ID';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.INSTRUMENT_NO IS '票据编号';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.BILL_NO IS '票据号码';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.BILL_TYPE IS '票据类型(银行承兑汇票/商业承兑汇票/电子汇票)';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.BILL_AMOUNT IS '票面金额';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.CURRENCY_CODE IS '币种';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.DRAWER IS '出票人';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.PAYEE IS '收款人';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.ACCEPTOR IS '承兑人';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.ISSUE_DATE IS '出票日期';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.MATURITY_DATE IS '到期日';
COMMENT ON COLUMN TBL_BILL_INSTRUMENT.BILL_STATUS IS '票据状态(已开立/已承兑/已背书/已贴现/已到期)';

CREATE INDEX IDX_INSTRUMENT_NO ON TBL_BILL_INSTRUMENT(INSTRUMENT_NO);
CREATE INDEX IDX_BILL_NO ON TBL_BILL_INSTRUMENT(BILL_NO);
CREATE INDEX IDX_BILL_TYPE ON TBL_BILL_INSTRUMENT(BILL_TYPE);
CREATE INDEX IDX_BILL_STATUS ON TBL_BILL_INSTRUMENT(BILL_STATUS);

-- 表2: 票据贴现表
DROP TABLE IF EXISTS TBL_BILL_DISCOUNT;

CREATE TABLE TBL_BILL_DISCOUNT (
    DISCOUNT_ID DECIMAL(20,0) PRIMARY KEY,
    DISCOUNT_NUMBER VARCHAR(50) NOT NULL,
    BILL_ID DECIMAL(20,0),
    DISCOUNT_TYPE VARCHAR(20),
    DISCOUNT_STATUS VARCHAR(20),
    DISCOUNT_BANK VARCHAR(200),
    DISCOUNT_RATE DECIMAL(10,6),
    DISCOUNT_AMOUNT DECIMAL(18,2),
    INTEREST_AMOUNT DECIMAL(18,2),
    HANDLING_FEE DECIMAL(18,2),
    ACTUAL_AMOUNT DECIMAL(18,2),
    APPLICATION_DATE TIMESTAMP,
    APPROVAL_DATE TIMESTAMP,
    MATURITY_DATE TIMESTAMP,
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP,
    CREATE_USER VARCHAR(50),
    UPDATE_USER VARCHAR(50),
    REMARK VARCHAR(500)
);

COMMENT ON TABLE TBL_BILL_DISCOUNT IS '票据贴现表';
COMMENT ON COLUMN TBL_BILL_DISCOUNT.DISCOUNT_ID IS '贴现ID';
COMMENT ON COLUMN TBL_BILL_DISCOUNT.DISCOUNT_NUMBER IS '贴现编号';
COMMENT ON COLUMN TBL_BILL_DISCOUNT.BILL_ID IS '票据ID';
COMMENT ON COLUMN TBL_BILL_DISCOUNT.DISCOUNT_TYPE IS '贴现类型(买断式/回购式)';
COMMENT ON COLUMN TBL_BILL_DISCOUNT.DISCOUNT_STATUS IS '贴现状态(申请中/已审批/已放款/已还款)';
COMMENT ON COLUMN TBL_BILL_DISCOUNT.DISCOUNT_RATE IS '贴现利率';
COMMENT ON COLUMN TBL_BILL_DISCOUNT.DISCOUNT_AMOUNT IS '贴现金额';
COMMENT ON COLUMN TBL_BILL_DISCOUNT.INTEREST_AMOUNT IS '贴现利息';

CREATE INDEX IDX_DISCOUNT_NUMBER ON TBL_BILL_DISCOUNT(DISCOUNT_NUMBER);
CREATE INDEX IDX_DISCOUNT_STATUS ON TBL_BILL_DISCOUNT(DISCOUNT_STATUS);

