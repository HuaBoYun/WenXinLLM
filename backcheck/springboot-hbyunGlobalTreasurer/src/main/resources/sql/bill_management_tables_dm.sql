    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP,
    CREATE_USER VARCHAR(50),
    UPDATE_USER VARCHAR(50),
    REMARK VARCHAR(500)
);

COMMENT ON TABLE TBL_BILL_MATURITY IS '票据到期管理表';
COMMENT ON COLUMN TBL_BILL_MATURITY.MATURITY_ID IS '到期ID';
COMMENT ON COLUMN TBL_BILL_MATURITY.BILL_ID IS '票据ID';
