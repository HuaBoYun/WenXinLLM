-- 安全参数配置表
CREATE TABLE IF NOT EXISTS TBL_TREASURY_PARAMETERS (
    PARAMID BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    PARAMCODE VARCHAR(50) NOT NULL COMMENT '参数编码',
    PARAMNAME VARCHAR(100) NOT NULL COMMENT '参数名称',
    PARAMVALUE VARCHAR(500) COMMENT '参数值',
    PARAMTYPE VARCHAR(20) NOT NULL COMMENT '参数类型：SYSTEM-系统参数，BUSINESS-业务参数，SECURITY-安全参数，INTERFACE-接口参数',
    DESCRIPTION VARCHAR(500) COMMENT '参数描述',
    ISENABLED INTEGER DEFAULT 1 COMMENT '是否启用：1-启用，0-停用',
    ISENCRYPTED INTEGER DEFAULT 0 COMMENT '是否加密：1-加密，0-不加密',
    ORGID BIGINT COMMENT '组织ID',
    CREATETIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    CREATEUSER BIGINT COMMENT '创建人ID',
    UPDATETIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
    UPDATEUSER BIGINT COMMENT '更新人ID'
);

-- 创建索引
CREATE INDEX IF NOT EXISTS IDX_TREASURY_PARAM_CODE ON TBL_TREASURY_PARAMETERS(PARAMCODE);
CREATE INDEX IF NOT EXISTS IDX_TREASURY_PARAM_TYPE ON TBL_TREASURY_PARAMETERS(PARAMTYPE);
CREATE INDEX IF NOT EXISTS IDX_TREASURY_PARAM_ENABLED ON TBL_TREASURY_PARAMETERS(ISENABLED);
CREATE INDEX IF NOT EXISTS IDX_TREASURY_PARAM_ORG ON TBL_TREASURY_PARAMETERS(ORGID);

-- 添加注释
COMMENT ON TABLE TBL_TREASURY_PARAMETERS IS '财资安全参数配置表';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.PARAMID IS '参数ID';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.PARAMCODE IS '参数编码';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.PARAMNAME IS '参数名称';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.PARAMVALUE IS '参数值';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.PARAMTYPE IS '参数类型';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.DESCRIPTION IS '参数描述';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.ISENABLED IS '是否启用';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.ISENCRYPTED IS '是否加密';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.ORGID IS '组织ID';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.CREATETIME IS '创建时间';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.CREATEUSER IS '创建人ID';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.UPDATETIME IS '更新时间';
COMMENT ON COLUMN TBL_TREASURY_PARAMETERS.UPDATEUSER IS '更新人ID';

