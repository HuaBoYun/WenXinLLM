-- 删除已存在的表(如果需要)
-- DROP TABLE IF EXISTS TC_ETICKET_ACCOUNT;

-- 创建电票账户配置表
CREATE TABLE TC_ETICKET_ACCOUNT (
    -- 主键
    ETICKET_ACCOUNT_ID DECIMAL(20,0) NOT NULL,

    -- 账户基本信息
    ACCOUNT_NUMBER VARCHAR(50) NOT NULL,
    ACCOUNT_NAME VARCHAR(200) NOT NULL,
    ETICKET_SYSTEM VARCHAR(50) NOT NULL,
    ACCOUNT_TYPE VARCHAR(50) NOT NULL,

    -- 银行信息
    BANK_NAME VARCHAR(200),
    BRANCH_NAME VARCHAR(200),
    BANK_CODE VARCHAR(50) NOT NULL,
    BANK_ACCOUNT_NUMBER VARCHAR(100) NOT NULL,

    -- 金额信息
    ACCOUNT_BALANCE DECIMAL(18,2) DEFAULT 0.00,
    CREDIT_LIMIT DECIMAL(18,2) DEFAULT 0.00,

    -- 账户状态
    OPEN_DATE DATE,
    ACCOUNT_STATUS VARCHAR(20) DEFAULT 'NORMAL',
    IS_ACTIVE INTEGER DEFAULT 1,

    -- 联系信息
    CONTACT_PERSON VARCHAR(100),
    CONTACT_PHONE VARCHAR(50),
    CONTACT_EMAIL VARCHAR(100),

    -- 备注和描述
    REMARK VARCHAR(500),
    DESCRIPTION VARCHAR(1000),

    -- 同步信息
    LAST_SYNC_TIME TIMESTAMP,
    SYNC_STATUS VARCHAR(20) DEFAULT 'PENDING',

    -- 组织信息
    ORG_ID DECIMAL(20,0),

    -- 审计字段
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATE_USER VARCHAR(50),
    UPDATE_USER VARCHAR(50),

    -- 主键约束
    CONSTRAINT PK_ETICKET_ACCOUNT PRIMARY KEY (ETICKET_ACCOUNT_ID)
);

-- 添加表注释
COMMENT ON TABLE TC_ETICKET_ACCOUNT IS '电票账户配置表';

-- 添加列注释
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.ETICKET_ACCOUNT_ID IS '电票账户ID(主键)';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.ACCOUNT_NUMBER IS '账户编号';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.ACCOUNT_NAME IS '账户名称';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.ETICKET_SYSTEM IS '电票系统(ECDS/BECP/BANK_ETICKET)';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.ACCOUNT_TYPE IS '账户类型(ACCEPTANCE/DISCOUNT/REDISCOUNT/PLEDGE/CUSTODY/MARGIN)';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.BANK_NAME IS '开户银行名称';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.BRANCH_NAME IS '分支机构名称';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.BANK_CODE IS '银行编码(ICBC/CCB/ABC/BOC/BOCOM/CMB等)';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.BANK_ACCOUNT_NUMBER IS '银行账号';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.ACCOUNT_BALANCE IS '账户余额';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.CREDIT_LIMIT IS '授信额度(万元)';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.OPEN_DATE IS '开户日期';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.ACCOUNT_STATUS IS '账户状态(NORMAL正常/FROZEN冻结/CLOSED关闭)';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.IS_ACTIVE IS '是否启用(1启用/0禁用)';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.CONTACT_PERSON IS '联系人姓名';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.CONTACT_PHONE IS '联系电话';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.CONTACT_EMAIL IS '联系邮箱';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.REMARK IS '备注信息';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.DESCRIPTION IS '描述信息';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.LAST_SYNC_TIME IS '最后同步时间';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.SYNC_STATUS IS '同步状态(SUCCESS成功/FAILED失败/PENDING待同步)';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.ORG_ID IS '组织ID';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.UPDATE_TIME IS '更新时间';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.CREATE_USER IS '创建人';
COMMENT ON COLUMN TC_ETICKET_ACCOUNT.UPDATE_USER IS '更新人';

-- 创建索引
CREATE UNIQUE INDEX IDX_ETICKET_ACCOUNT_NUMBER ON TC_ETICKET_ACCOUNT(ACCOUNT_NUMBER);
CREATE INDEX IDX_ETICKET_ACCOUNT_NAME ON TC_ETICKET_ACCOUNT(ACCOUNT_NAME);
CREATE INDEX IDX_ETICKET_SYSTEM ON TC_ETICKET_ACCOUNT(ETICKET_SYSTEM);
CREATE INDEX IDX_ETICKET_TYPE ON TC_ETICKET_ACCOUNT(ACCOUNT_TYPE);
CREATE INDEX IDX_ETICKET_BANK_CODE ON TC_ETICKET_ACCOUNT(BANK_CODE);
CREATE INDEX IDX_ETICKET_STATUS ON TC_ETICKET_ACCOUNT(ACCOUNT_STATUS);
CREATE INDEX IDX_ETICKET_ORG_ID ON TC_ETICKET_ACCOUNT(ORG_ID);
CREATE INDEX IDX_ETICKET_CREATE_TIME ON TC_ETICKET_ACCOUNT(CREATE_TIME);

-- 添加索引注释
COMMENT ON INDEX IDX_ETICKET_ACCOUNT_NUMBER IS '账户编号唯一索引';
COMMENT ON INDEX IDX_ETICKET_ACCOUNT_NAME IS '账户名称索引';
COMMENT ON INDEX IDX_ETICKET_SYSTEM IS '电票系统索引';
COMMENT ON INDEX IDX_ETICKET_TYPE IS '账户类型索引';
COMMENT ON INDEX IDX_ETICKET_BANK_CODE IS '银行编码索引';
COMMENT ON INDEX IDX_ETICKET_STATUS IS '账户状态索引';
COMMENT ON INDEX IDX_ETICKET_ORG_ID IS '组织ID索引';
COMMENT ON INDEX IDX_ETICKET_CREATE_TIME IS '创建时间索引';

