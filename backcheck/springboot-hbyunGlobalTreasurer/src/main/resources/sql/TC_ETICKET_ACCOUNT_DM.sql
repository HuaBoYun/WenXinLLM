-- 电票账户配置表 - 达梦数据库建表脚本
-- 表名: TC_ETICKET_ACCOUNT
-- 描述: 存储电子票据账户的配置信息,包括账户基本信息、银行信息、额度信息等
-- 作者: 华博云开发团队
