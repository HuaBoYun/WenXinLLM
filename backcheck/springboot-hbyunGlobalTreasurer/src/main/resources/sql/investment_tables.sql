CREATE INDEX IDX_BANK_INVESTMENT_COMPANY ON TBL_BANK_WEALTH_INVESTMENT(COMPANY_ID);

COMMENT ON TABLE TBL_BANK_WEALTH_INVESTMENT IS '银行理财投资表';
COMMENT ON COLUMN TBL_BANK_WEALTH_INVESTMENT.INVESTMENT_ID IS '投资ID';
COMMENT ON COLUMN TBL_BANK_WEALTH_INVESTMENT.INVESTMENT_STATUS IS '投资状态(PENDING/ACTIVE/MATURED/REDEEMED)';

-- 5. 债券投资表
CREATE TABLE TBL_BOND_INVESTMENT (
    INVESTMENT_ID           BIGINT          NOT NULL,
    INVESTMENT_NO           VARCHAR(50)     NOT NULL,
    BOND_CODE               VARCHAR(50)     NOT NULL,
    BOND_NAME               VARCHAR(200)    NOT NULL,
    BOND_TYPE               VARCHAR(50)     NOT NULL,
    ISSUER                  VARCHAR(200)    NOT NULL,
    CREDIT_RATING           VARCHAR(20),
    FACE_VALUE              DECIMAL(18,2)   NOT NULL,
    PURCHASE_PRICE          DECIMAL(18,4)   NOT NULL,
    PURCHASE_QUANTITY       INT             NOT NULL,
    INVESTMENT_AMOUNT       DECIMAL(18,2)   NOT NULL,
    COUPON_RATE             DECIMAL(10,4)   NOT NULL,
    YIELD_TO_MATURITY       DECIMAL(10,4),
    COUPON_FREQUENCY        VARCHAR(20),
    PURCHASE_DATE           DATE            NOT NULL,
    MATURITY_DATE           DATE            NOT NULL,
    NEXT_COUPON_DATE        DATE,
    ACCUMULATED_INTEREST    DECIMAL(18,2)   DEFAULT 0,
    CURRENT_MARKET_VALUE    DECIMAL(18,2),
    UNREALIZED_PNL          DECIMAL(18,2)   DEFAULT 0,
    RISK_LEVEL              VARCHAR(20)     NOT NULL,
    INVESTMENT_STATUS       VARCHAR(20)     DEFAULT 'HOLDING',
    CURRENCY_CODE           VARCHAR(10)     DEFAULT 'CNY',
    PLAN_ID                 BIGINT,
    PLAN_NO                 VARCHAR(50),
    COMPANY_ID              BIGINT,
    COMPANY_NAME            VARCHAR(200),
    DELETE_FLAG             INT             DEFAULT 0,
    CREATED_BY              BIGINT,
    CREATED_BY_NAME         VARCHAR(100),
    CREATED_TIME            TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY              BIGINT,
    UPDATED_BY_NAME         VARCHAR(100),
    UPDATED_TIME            TIMESTAMP,
    REMARK                  VARCHAR(500),
    PRIMARY KEY (INVESTMENT_ID)
);

CREATE UNIQUE INDEX IDX_BOND_INVESTMENT_NO ON TBL_BOND_INVESTMENT(INVESTMENT_NO);
CREATE INDEX IDX_BOND_CODE ON TBL_BOND_INVESTMENT(BOND_CODE);
CREATE INDEX IDX_BOND_TYPE ON TBL_BOND_INVESTMENT(BOND_TYPE);
CREATE INDEX IDX_BOND_INVESTMENT_STATUS ON TBL_BOND_INVESTMENT(INVESTMENT_STATUS);
CREATE INDEX IDX_BOND_MATURITY ON TBL_BOND_INVESTMENT(MATURITY_DATE);
CREATE INDEX IDX_BOND_COMPANY ON TBL_BOND_INVESTMENT(COMPANY_ID);

COMMENT ON TABLE TBL_BOND_INVESTMENT IS '债券投资表';
COMMENT ON COLUMN TBL_BOND_INVESTMENT.INVESTMENT_ID IS '投资ID';
COMMENT ON COLUMN TBL_BOND_INVESTMENT.BOND_TYPE IS '债券类型(GOVERNMENT/CORPORATE/FINANCIAL/LOCAL)';
COMMENT ON COLUMN TBL_BOND_INVESTMENT.INVESTMENT_STATUS IS '投资状态(HOLDING/SOLD/MATURED)';

