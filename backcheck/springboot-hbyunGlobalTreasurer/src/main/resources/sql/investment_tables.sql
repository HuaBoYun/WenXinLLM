-- 1. 投资产品表
CREATE TABLE TBL_INVESTMENT_PRODUCT (
    PRODUCT_ID              BIGINT          NOT NULL,
    PRODUCT_CODE            VARCHAR(50)     NOT NULL,
    PRODUCT_NAME            VARCHAR(200)    NOT NULL,
    PRODUCT_TYPE            VARCHAR(50)     NOT NULL,
    ISSUER                  VARCHAR(200),
    RISK_LEVEL              VARCHAR(20)     NOT NULL,
    EXPECTED_RETURN_RATE    DECIMAL(10,4),
    MIN_INVESTMENT_AMOUNT   DECIMAL(18,2),
    MAX_INVESTMENT_AMOUNT   DECIMAL(18,2),
    INVESTMENT_TERM         INT,
    NET_VALUE               DECIMAL(10,4)   DEFAULT 1.0000,
    LAUNCH_DATE             DATE,
    MATURITY_DATE           DATE,
    SUBSCRIPTION_START_DATE DATE,
    SUBSCRIPTION_END_DATE   DATE,
    REDEMPTION_ALLOWED      INT             DEFAULT 1,
    PRODUCT_STATUS          VARCHAR(20)     DEFAULT 'ACTIVE',
    PRODUCT_DESCRIPTION     VARCHAR(2000),
    SUSPEND_REASON          VARCHAR(500),
    CURRENCY_CODE           VARCHAR(10)     DEFAULT 'CNY',
    COMPANY_ID              BIGINT,
    COMPANY_NAME            VARCHAR(200),
    DELETE_FLAG             INT             DEFAULT 0,
    CREATED_BY              BIGINT,
    CREATED_BY_NAME         VARCHAR(100),
    CREATED_TIME            TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY              BIGINT,
    UPDATED_BY_NAME         VARCHAR(100),
    UPDATED_TIME            TIMESTAMP,
    REMARK                  VARCHAR(500),
    PRIMARY KEY (PRODUCT_ID)
);

CREATE UNIQUE INDEX IDX_PRODUCT_CODE ON TBL_INVESTMENT_PRODUCT(PRODUCT_CODE);
CREATE INDEX IDX_PRODUCT_TYPE ON TBL_INVESTMENT_PRODUCT(PRODUCT_TYPE);
CREATE INDEX IDX_PRODUCT_STATUS ON TBL_INVESTMENT_PRODUCT(PRODUCT_STATUS);
CREATE INDEX IDX_PRODUCT_COMPANY ON TBL_INVESTMENT_PRODUCT(COMPANY_ID);

COMMENT ON TABLE TBL_INVESTMENT_PRODUCT IS '投资产品表';
COMMENT ON COLUMN TBL_INVESTMENT_PRODUCT.PRODUCT_ID IS '产品ID';
COMMENT ON COLUMN TBL_INVESTMENT_PRODUCT.PRODUCT_CODE IS '产品代码';
COMMENT ON COLUMN TBL_INVESTMENT_PRODUCT.PRODUCT_NAME IS '产品名称';
COMMENT ON COLUMN TBL_INVESTMENT_PRODUCT.PRODUCT_TYPE IS '产品类型';
COMMENT ON COLUMN TBL_INVESTMENT_PRODUCT.RISK_LEVEL IS '风险等级(LOW/MEDIUM/HIGH)';
COMMENT ON COLUMN TBL_INVESTMENT_PRODUCT.PRODUCT_STATUS IS '产品状态(ACTIVE/SUSPENDED)';

-- 2. 投资计划表
CREATE TABLE TBL_INVESTMENT_PLAN (
    PLAN_ID                 BIGINT          NOT NULL,
    PLAN_NO                 VARCHAR(50)     NOT NULL,
    PLAN_NAME               VARCHAR(200)    NOT NULL,
    INVESTMENT_TYPE         VARCHAR(50)     NOT NULL,
    RISK_LEVEL              VARCHAR(20)     NOT NULL,
    PLAN_AMOUNT             DECIMAL(18,2)   NOT NULL,
    INVESTED_AMOUNT         DECIMAL(18,2)   DEFAULT 0,
    EXPECTED_RETURN_RATE    DECIMAL(10,4),
    ACTUAL_RETURN_RATE      DECIMAL(10,4),
    PLAN_START_DATE         DATE            NOT NULL,
    PLAN_END_DATE           DATE            NOT NULL,
    PLAN_STATUS             VARCHAR(20)     DEFAULT 'DRAFT',
    PLAN_DESCRIPTION        VARCHAR(2000),
    APPROVAL_COMMENTS       VARCHAR(500),
    APPROVED_BY             BIGINT,
    APPROVED_BY_NAME        VARCHAR(100),
    APPROVAL_TIME           TIMESTAMP,
    REJECTION_REASON        VARCHAR(500),
    COMPLETION_NOTES        VARCHAR(500),
    CANCEL_REASON           VARCHAR(500),
    CURRENCY_CODE           VARCHAR(10)     DEFAULT 'CNY',
    COMPANY_ID              BIGINT,
    COMPANY_NAME            VARCHAR(200),
    DELETE_FLAG             INT             DEFAULT 0,
    CREATED_BY              BIGINT,
    CREATED_BY_NAME         VARCHAR(100),
    CREATED_TIME            TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY              BIGINT,
    UPDATED_BY_NAME         VARCHAR(100),
    UPDATED_TIME            TIMESTAMP,
    REMARK                  VARCHAR(500),
    PRIMARY KEY (PLAN_ID)
);

CREATE UNIQUE INDEX IDX_PLAN_NO ON TBL_INVESTMENT_PLAN(PLAN_NO);
CREATE INDEX IDX_PLAN_STATUS ON TBL_INVESTMENT_PLAN(PLAN_STATUS);
CREATE INDEX IDX_PLAN_TYPE ON TBL_INVESTMENT_PLAN(INVESTMENT_TYPE);
CREATE INDEX IDX_PLAN_COMPANY ON TBL_INVESTMENT_PLAN(COMPANY_ID);

COMMENT ON TABLE TBL_INVESTMENT_PLAN IS '投资计划表';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_ID IS '计划ID';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_NO IS '计划编号';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_STATUS IS '计划状态(DRAFT/SUBMITTED/APPROVED/EXECUTING/COMPLETED/CANCELLED)';

-- 3. 投资监控表
CREATE TABLE TBL_INVESTMENT_MONITORING (
    MONITORING_ID           BIGINT          NOT NULL,
    INVESTMENT_ID           BIGINT          NOT NULL,
    INVESTMENT_TYPE         VARCHAR(50),
    MONITORING_DATE         DATE            NOT NULL,
    MONITORING_TYPE         VARCHAR(20)     NOT NULL,
    PREVIOUS_VALUE          DECIMAL(18,2),
    CURRENT_VALUE           DECIMAL(18,2),
    VALUE_CHANGE            DECIMAL(18,2),
    VALUE_CHANGE_RATE       DECIMAL(10,4),
    PERFORMANCE_SCORE       INT,
    RISK_SCORE              INT,
    ALERT_LEVEL             VARCHAR(20),
    ALERT_MESSAGE           VARCHAR(500),
    ALERT_TYPE              VARCHAR(50),
    ALERT_STATUS            VARCHAR(20)     DEFAULT 'PENDING',
    MONITORING_STATUS       VARCHAR(20)     DEFAULT 'ACTIVE',
    MONITORING_NOTES        VARCHAR(1000),
    COMPANY_ID              BIGINT,
    COMPANY_NAME            VARCHAR(200),
    DELETE_FLAG             INT             DEFAULT 0,
    CREATED_BY              BIGINT,
    CREATED_BY_NAME         VARCHAR(100),
    CREATED_TIME            TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY              BIGINT,
    UPDATED_BY_NAME         VARCHAR(100),
    UPDATED_TIME            TIMESTAMP,
    REMARK                  VARCHAR(500),
    PRIMARY KEY (MONITORING_ID)
);

CREATE INDEX IDX_MONITORING_INVESTMENT ON TBL_INVESTMENT_MONITORING(INVESTMENT_ID);
CREATE INDEX IDX_MONITORING_DATE ON TBL_INVESTMENT_MONITORING(MONITORING_DATE);
CREATE INDEX IDX_MONITORING_ALERT ON TBL_INVESTMENT_MONITORING(ALERT_LEVEL, ALERT_STATUS);

COMMENT ON TABLE TBL_INVESTMENT_MONITORING IS '投资监控表';
COMMENT ON COLUMN TBL_INVESTMENT_MONITORING.MONITORING_ID IS '监控ID';
COMMENT ON COLUMN TBL_INVESTMENT_MONITORING.ALERT_LEVEL IS '预警级别(LOW/MEDIUM/HIGH)';
COMMENT ON COLUMN TBL_INVESTMENT_MONITORING.ALERT_STATUS IS '预警状态(PENDING/PROCESSED)';

