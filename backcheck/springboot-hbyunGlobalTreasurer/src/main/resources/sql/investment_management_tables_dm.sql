-- 1. 投资计划表 (TBL_INVESTMENT_PLAN)
CREATE TABLE IF NOT EXISTS TBL_INVESTMENT_PLAN (
    PLAN_ID BIGINT PRIMARY KEY,
    PLAN_NO VARCHAR(50) NOT NULL,
    PLAN_NAME VARCHAR(200) NOT NULL,
    PLAN_TYPE VARCHAR(50),
    INVESTMENT_TYPE VARCHAR(50),
    PLAN_AMOUNT DECIMAL(20,2),
    INVESTED_AMOUNT DECIMAL(20,2) DEFAULT 0,
    REMAINING_AMOUNT DECIMAL(20,2),
    EXPECTED_RETURN_RATE DECIMAL(10,6),
    ACTUAL_RETURN_RATE DECIMAL(10,6),
    RISK_LEVEL VARCHAR(20),
    PLAN_STATUS VARCHAR(20) DEFAULT 'DRAFT',
    PLAN_START_DATE DATE,
    PLAN_END_DATE DATE,
    PLAN_DESCRIPTION CLOB,
    APPROVAL_COMMENTS VARCHAR(500),
    REJECTION_REASON VARCHAR(500),
    COMPLETION_NOTES VARCHAR(500),
    CANCEL_REASON VARCHAR(500),
    COMPANY_ID BIGINT,
    COMPANY_NAME VARCHAR(200),
    CREATED_BY BIGINT,
    CREATED_BY_NAME VARCHAR(100),
    CREATED_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY BIGINT,
    UPDATED_BY_NAME VARCHAR(100),
    UPDATED_TIME TIMESTAMP,
    DELETE_FLAG INT DEFAULT 0,
    REMARK VARCHAR(500)
);

-- 投资计划表索引
CREATE INDEX IF NOT EXISTS IDX_INVESTMENT_PLAN_NO ON TBL_INVESTMENT_PLAN(PLAN_NO);
CREATE INDEX IF NOT EXISTS IDX_INVESTMENT_PLAN_STATUS ON TBL_INVESTMENT_PLAN(PLAN_STATUS);
CREATE INDEX IF NOT EXISTS IDX_INVESTMENT_PLAN_TYPE ON TBL_INVESTMENT_PLAN(INVESTMENT_TYPE);
CREATE INDEX IF NOT EXISTS IDX_INVESTMENT_PLAN_COMPANY ON TBL_INVESTMENT_PLAN(COMPANY_ID);

-- 投资计划表注释
COMMENT ON TABLE TBL_INVESTMENT_PLAN IS '投资计划表';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_ID IS '计划ID';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_NO IS '计划编号';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_NAME IS '计划名称';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_TYPE IS '计划类型';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.INVESTMENT_TYPE IS '投资类型(BANK_WEALTH-银行理财,BOND-债券,EQUITY-股权,FUND-基金,DERIVATIVE-衍生品)';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_AMOUNT IS '计划金额';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.INVESTED_AMOUNT IS '已投资金额';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.REMAINING_AMOUNT IS '剩余金额';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.EXPECTED_RETURN_RATE IS '预期收益率';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.ACTUAL_RETURN_RATE IS '实际收益率';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.RISK_LEVEL IS '风险等级(LOW-低,MEDIUM-中,HIGH-高)';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_STATUS IS '计划状态(DRAFT-草稿,SUBMITTED-已提交,APPROVED-已审批,EXECUTING-执行中,COMPLETED-已完成,CANCELLED-已取消)';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_START_DATE IS '开始日期';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_END_DATE IS '结束日期';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.PLAN_DESCRIPTION IS '计划描述';
COMMENT ON COLUMN TBL_INVESTMENT_PLAN.DELETE_FLAG IS '删除标志(0-正常,1-删除)';

