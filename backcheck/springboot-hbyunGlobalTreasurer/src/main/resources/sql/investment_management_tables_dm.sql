-- 4. 投资监控表 (TBL_INVESTMENT_MONITORING)
CREATE TABLE IF NOT EXISTS TBL_INVESTMENT_MONITORING (
    MONITORING_ID BIGINT PRIMARY KEY,
    INVESTMENT_ID BIGINT,
    INVESTMENT_TYPE VARCHAR(50),
    MONITORING_DATE DATE,
    MONITORING_TYPE VARCHAR(50),
    CURRENT_VALUE DECIMAL(20,2),
    PREVIOUS_VALUE DECIMAL(20,2),
    VALUE_CHANGE DECIMAL(20,2),
    VALUE_CHANGE_RATE DECIMAL(10,6),
    RISK_SCORE DECIMAL(10,2),
    RISK_LEVEL VARCHAR(20),
    ALERT_STATUS VARCHAR(20) DEFAULT 'NORMAL',
    ALERT_TYPE VARCHAR(50),
    ALERT_MESSAGE VARCHAR(500),
    ALERT_TIME TIMESTAMP,
    HANDLE_STATUS VARCHAR(20) DEFAULT 'PENDING',
    HANDLE_RESULT VARCHAR(500),
    HANDLE_TIME TIMESTAMP,
    HANDLER_ID BIGINT,
    HANDLER_NAME VARCHAR(100),
    COMPANY_ID BIGINT,
    COMPANY_NAME VARCHAR(200),
    CREATED_BY BIGINT,
    CREATED_BY_NAME VARCHAR(100),
    CREATED_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY BIGINT,
    UPDATED_BY_NAME VARCHAR(100),
    UPDATED_TIME TIMESTAMP,
    DELETE_FLAG INT DEFAULT 0,
    REMARK VARCHAR(500)
);

-- 投资监控表索引
CREATE INDEX IF NOT EXISTS IDX_INV_MONITOR_INV ON TBL_INVESTMENT_MONITORING(INVESTMENT_ID);
CREATE INDEX IF NOT EXISTS IDX_INV_MONITOR_TYPE ON TBL_INVESTMENT_MONITORING(INVESTMENT_TYPE);
CREATE INDEX IF NOT EXISTS IDX_INV_MONITOR_DATE ON TBL_INVESTMENT_MONITORING(MONITORING_DATE);
CREATE INDEX IF NOT EXISTS IDX_INV_MONITOR_ALERT ON TBL_INVESTMENT_MONITORING(ALERT_STATUS);

-- 投资监控表注释
