    BUSINESS_DOC_NO VARCHAR2(50),
    BUSINESS_TYPE VARCHAR2(50),
    USAGE_PURPOSE VARCHAR2(200),
    USAGE_USER VARCHAR2(32),
    USAGE_TIME DATE,
    USAGE_LOCATION VARCHAR2(100),
    APPROVAL_USER VARCHAR2(32),
    APPROVAL_TIME DATE,
    USAGE_RESULT VARCHAR2(20),
    EXCEPTION_REASON VARCHAR2(500),
    IP_ADDRESS VARCHAR2(50),
    MAC_ADDRESS VARCHAR2(50),
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_SEAL_USAGE_LOG PRIMARY KEY (ID),
    CONSTRAINT FK_TC_SEAL_USAGE_LOG_COMB FOREIGN KEY (COMBINATION_ID) REFERENCES TC_SEAL_COMBINATION(ID),
    CONSTRAINT FK_TC_SEAL_USAGE_LOG_SEAL FOREIGN KEY (SEAL_ID) REFERENCES TC_SEAL_ARCHIVE(ID)
);

