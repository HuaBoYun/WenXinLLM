    SORT_ORDER NUMBER(5) DEFAULT 0,
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_SEAL_TYPE PRIMARY KEY (ID),
    CONSTRAINT UK_TC_SEAL_TYPE_CODE UNIQUE (TYPE_CODE)
);

-- 6. 印鉴档案表
CREATE TABLE TC_SEAL_ARCHIVE (
    ID VARCHAR2(32) NOT NULL,
    SEAL_CODE VARCHAR2(50) NOT NULL,
    SEAL_NAME VARCHAR2(100) NOT NULL,
    SEAL_TYPE_ID VARCHAR2(32) NOT NULL,
    SEAL_SPEC VARCHAR2(50),
    SEAL_MATERIAL VARCHAR2(50),
    SEAL_IMAGE_PATH VARCHAR2(500),
    OWNER_NAME VARCHAR2(50),
    OWNER_POSITION VARCHAR2(50),
    USAGE_PERMISSION VARCHAR2(100),
    SEAL_STATUS VARCHAR2(20) DEFAULT 'NORMAL',
    EFFECTIVE_DATE DATE,
    EXPIRE_DATE DATE,
    LOSS_REPORT_DATE DATE,
    CANCEL_DATE DATE,
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_SEAL_ARCHIVE PRIMARY KEY (ID),
    CONSTRAINT UK_TC_SEAL_ARCHIVE_CODE UNIQUE (SEAL_CODE),
    CONSTRAINT FK_TC_SEAL_ARCHIVE_TYPE FOREIGN KEY (SEAL_TYPE_ID) REFERENCES TC_SEAL_TYPE(ID)
);

-- 7. 印鉴组合表
CREATE TABLE TC_SEAL_COMBINATION (
    ID VARCHAR2(32) NOT NULL,
    COMBINATION_CODE VARCHAR2(50) NOT NULL,
    COMBINATION_NAME VARCHAR2(100) NOT NULL,
    BUSINESS_SCENARIO VARCHAR2(100),
    COMBINATION_DESC VARCHAR2(500),
    APPROVAL_LEVEL VARCHAR2(20),
    USAGE_RULE VARCHAR2(500),
    TIME_LIMIT VARCHAR2(100),
    LOCATION_LIMIT VARCHAR2(100),
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_SEAL_COMBINATION PRIMARY KEY (ID),
    CONSTRAINT UK_TC_SEAL_COMBINATION_CODE UNIQUE (COMBINATION_CODE)
