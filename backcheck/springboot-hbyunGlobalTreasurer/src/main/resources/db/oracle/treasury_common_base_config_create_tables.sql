-- 印鉴组合明细表索引
CREATE INDEX IDX_TC_SEAL_COMB_DETAIL_COMB ON TC_SEAL_COMBINATION_DETAIL(COMBINATION_ID);
CREATE INDEX IDX_TC_SEAL_COMB_DETAIL_SEAL ON TC_SEAL_COMBINATION_DETAIL(SEAL_ID);

-- 印鉴使用记录表索引
CREATE INDEX IDX_TC_SEAL_USAGE_LOG_COMB ON TC_SEAL_USAGE_LOG(COMBINATION_ID);
CREATE INDEX IDX_TC_SEAL_USAGE_LOG_SEAL ON TC_SEAL_USAGE_LOG(SEAL_ID);
CREATE INDEX IDX_TC_SEAL_USAGE_LOG_USER ON TC_SEAL_USAGE_LOG(USAGE_USER);
CREATE INDEX IDX_TC_SEAL_USAGE_LOG_TIME ON TC_SEAL_USAGE_LOG(USAGE_TIME);
CREATE INDEX IDX_TC_SEAL_USAGE_LOG_DOC ON TC_SEAL_USAGE_LOG(BUSINESS_DOC_NO);

-- 虚拟账户表索引
CREATE INDEX IDX_TC_VIRTUAL_ACCOUNT_TYPE ON TC_VIRTUAL_ACCOUNT(ACCOUNT_TYPE);
CREATE INDEX IDX_TC_VIRTUAL_ACCOUNT_STATUS ON TC_VIRTUAL_ACCOUNT(STATUS);
CREATE INDEX IDX_TC_VIRTUAL_ACCOUNT_SYNC ON TC_VIRTUAL_ACCOUNT(SYNC_STATUS);

-- 电票账户设置表索引
CREATE INDEX IDX_TC_ETICKET_ACCOUNT_BANK ON TC_ETICKET_ACCOUNT(BANK_CODE);
