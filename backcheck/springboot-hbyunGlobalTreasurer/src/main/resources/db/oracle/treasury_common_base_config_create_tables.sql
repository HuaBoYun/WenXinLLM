CREATE INDEX IDX_TC_SECURITY_CONFIG_TYPE ON TC_SECURITY_CONFIG(CONFIG_TYPE);
CREATE INDEX IDX_TC_SECURITY_CONFIG_STATUS ON TC_SECURITY_CONFIG(STATUS);

-- 业务系统注册表索引
CREATE INDEX IDX_TC_BUSINESS_SYSTEM_TYPE ON TC_BUSINESS_SYSTEM(SYSTEM_TYPE);
