-- 8. 印鉴组合明细表
CREATE TABLE TC_SEAL_COMBINATION_DETAIL (
    ID VARCHAR2(32) NOT NULL,
    COMBINATION_ID VARCHAR2(32) NOT NULL,
    SEAL_ID VARCHAR2(32) NOT NULL,
    IS_REQUIRED VARCHAR2(1) DEFAULT '1',
    USAGE_ORDER NUMBER(3) DEFAULT 1,
    ALTERNATIVE_SEAL_ID VARCHAR2(32),
    USAGE_CONDITION VARCHAR2(200),
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_SEAL_COMBINATION_DETAIL PRIMARY KEY (ID),
    CONSTRAINT FK_TC_SEAL_COMB_DETAIL_COMB FOREIGN KEY (COMBINATION_ID) REFERENCES TC_SEAL_COMBINATION(ID),
    CONSTRAINT FK_TC_SEAL_COMB_DETAIL_SEAL FOREIGN KEY (SEAL_ID) REFERENCES TC_SEAL_ARCHIVE(ID),
    CONSTRAINT FK_TC_SEAL_COMB_DETAIL_ALT FOREIGN KEY (ALTERNATIVE_SEAL_ID) REFERENCES TC_SEAL_ARCHIVE(ID)
);

-- 9. 印鉴使用记录表
CREATE TABLE TC_SEAL_USAGE_LOG (
    ID VARCHAR2(32) NOT NULL,
