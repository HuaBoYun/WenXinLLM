-- 1. Ukey厂商管理表
CREATE TABLE TC_UKEY_VENDOR (
    ID VARCHAR2(32) NOT NULL,
    VENDOR_CODE VARCHAR2(20) NOT NULL,
    VENDOR_NAME VARCHAR2(100) NOT NULL,
    VENDOR_SHORT_NAME VARCHAR2(50),
    VENDOR_EN_NAME VARCHAR2(100),
    ESTABLISH_DATE DATE,
    REGISTER_ADDRESS VARCHAR2(500),
    BUSINESS_SCOPE VARCHAR2(1000),
    CONTACT_PHONE VARCHAR2(50),
    TECH_SUPPORT_PHONE VARCHAR2(50),
    OFFICIAL_WEBSITE VARCHAR2(200),
    LICENSE_NO VARCHAR2(50),
    TECH_CERT_NO VARCHAR2(50),
    SECURITY_LEVEL VARCHAR2(20),
    ENCRYPTION_ALGORITHMS VARCHAR2(200),
    STORAGE_CAPACITY VARCHAR2(50),
    CERT_LIMIT NUMBER(10),
    PIN_LENGTH_REQ NUMBER(2),
    DRIVER_VERSION VARCHAR2(50),
    INTERFACE_PROTOCOL VARCHAR2(50),
    SERVICE_RATING VARCHAR2(10),
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_UKEY_VENDOR PRIMARY KEY (ID),
    CONSTRAINT UK_TC_UKEY_VENDOR_CODE UNIQUE (VENDOR_CODE)
);

-- 2. 安全配置表
CREATE TABLE TC_SECURITY_CONFIG (
    ID VARCHAR2(32) NOT NULL,
    CONFIG_TYPE VARCHAR2(50) NOT NULL,
    CONFIG_KEY VARCHAR2(100) NOT NULL,
    CONFIG_VALUE VARCHAR2(500),
    CONFIG_DESC VARCHAR2(200),
    DEFAULT_VALUE VARCHAR2(500),
    VALUE_TYPE VARCHAR2(20) DEFAULT 'STRING',
    IS_REQUIRED VARCHAR2(1) DEFAULT '0',
    SORT_ORDER NUMBER(5) DEFAULT 0,
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_SECURITY_CONFIG PRIMARY KEY (ID),
    CONSTRAINT UK_TC_SECURITY_CONFIG_KEY UNIQUE (CONFIG_TYPE, CONFIG_KEY)
);

-- 3. 业务系统注册表
CREATE TABLE TC_BUSINESS_SYSTEM (
    ID VARCHAR2(32) NOT NULL,
    SYSTEM_CODE VARCHAR2(50) NOT NULL,
    SYSTEM_NAME VARCHAR2(100) NOT NULL,
    SYSTEM_TYPE VARCHAR2(50),
    SYSTEM_DESC VARCHAR2(500),
    INTERFACE_URL VARCHAR2(200),
    INTERFACE_PORT NUMBER(5),
    AUTH_TYPE VARCHAR2(20),
    AUTH_CONFIG VARCHAR2(1000),
    DATA_FORMAT VARCHAR2(20),
    CONNECTION_STATUS VARCHAR2(20),
    LAST_CONNECT_TIME DATE,
    CONNECT_TIMEOUT NUMBER(10) DEFAULT 30000,
    READ_TIMEOUT NUMBER(10) DEFAULT 60000,
    RETRY_COUNT NUMBER(2) DEFAULT 3,
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_BUSINESS_SYSTEM PRIMARY KEY (ID),
    CONSTRAINT UK_TC_BUSINESS_SYSTEM_CODE UNIQUE (SYSTEM_CODE)
);

-- 4. 数据映射配置表
CREATE TABLE TC_DATA_MAPPING (
    ID VARCHAR2(32) NOT NULL,
    SYSTEM_ID VARCHAR2(32) NOT NULL,
    MAPPING_NAME VARCHAR2(100),
    SOURCE_FIELD VARCHAR2(100) NOT NULL,
    TARGET_FIELD VARCHAR2(100) NOT NULL,
    FIELD_TYPE VARCHAR2(20),
    CONVERSION_RULE VARCHAR2(500),
    DEFAULT_VALUE VARCHAR2(200),
    IS_REQUIRED VARCHAR2(1) DEFAULT '0',
    VALIDATION_RULE VARCHAR2(500),
    ERROR_STRATEGY VARCHAR2(20) DEFAULT 'IGNORE',
    SORT_ORDER NUMBER(5) DEFAULT 0,
    STATUS VARCHAR2(10) DEFAULT '1',
    REMARK VARCHAR2(500),
    CREATE_TIME DATE DEFAULT SYSDATE,
    UPDATE_TIME DATE DEFAULT SYSDATE,
    CREATE_USER VARCHAR2(32),
    UPDATE_USER VARCHAR2(32),
    VERSION_NO NUMBER(10) DEFAULT 0,
    CONSTRAINT PK_TC_DATA_MAPPING PRIMARY KEY (ID),
    CONSTRAINT FK_TC_DATA_MAPPING_SYSTEM FOREIGN KEY (SYSTEM_ID) REFERENCES TC_BUSINESS_SYSTEM(ID)
);

-- 5. 印鉴类型表
CREATE TABLE TC_SEAL_TYPE (
