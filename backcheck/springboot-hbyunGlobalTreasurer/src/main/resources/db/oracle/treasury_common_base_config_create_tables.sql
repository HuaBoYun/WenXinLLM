-- 印鉴类型表索引
CREATE INDEX IDX_TC_SEAL_TYPE_STATUS ON TC_SEAL_TYPE(STATUS);

-- 印鉴档案表索引
CREATE INDEX IDX_TC_SEAL_ARCHIVE_TYPE ON TC_SEAL_ARCHIVE(SEAL_TYPE_ID);
CREATE INDEX IDX_TC_SEAL_ARCHIVE_STATUS ON TC_SEAL_ARCHIVE(STATUS);
CREATE INDEX IDX_TC_SEAL_ARCHIVE_SEAL_STATUS ON TC_SEAL_ARCHIVE(SEAL_STATUS);
