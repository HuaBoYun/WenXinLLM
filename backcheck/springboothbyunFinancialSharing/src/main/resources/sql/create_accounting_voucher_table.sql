COMMENT ON COLUMN T_ACCOUNTING_VOUCHER.VOUCHER_DESC IS '凭证摘要';
COMMENT ON COLUMN T_ACCOUNTING_VOUCHER.TOTAL_DEBIT IS '借方金额合计';
COMMENT ON COLUMN T_ACCOUNTING_VOUCHER.TOTAL_CREDIT IS '贷方金额合计';
COMMENT ON COLUMN T_ACCOUNTING_VOUCHER.ENTRY_COUNT IS '分录数量';
COMMENT ON COLUMN T_ACCOUNTING_VOUCHER.VOUCHER_STATUS IS '凭证状态(0草稿1已生成2已过账3已取消)';
COMMENT ON COLUMN T_ACCOUNTING_VOUCHER.SOURCE_TRANSACTION_ID IS '来源事项ID';
