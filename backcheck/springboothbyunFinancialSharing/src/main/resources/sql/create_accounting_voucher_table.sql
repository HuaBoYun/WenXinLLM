-- 创建会计凭证表
CREATE TABLE T_ACCOUNTING_VOUCHER (
    VOUCHER_ID NUMBER(20) NOT NULL PRIMARY KEY COMMENT '凭证ID',
    VOUCHER_NO VARCHAR2(50) NOT NULL COMMENT '凭证编号',
    VOUCHER_TYPE_ID NUMBER(20) COMMENT '凭证类型ID',
    VOUCHER_DATE DATE COMMENT '凭证日期',
    ACCOUNTING_PERIOD VARCHAR2(20) COMMENT '会计期间',
    VOUCHER_DESC VARCHAR2(500) COMMENT '凭证摘要',
    TOTAL_DEBIT NUMBER(18,2) COMMENT '借方金额合计',
    TOTAL_CREDIT NUMBER(18,2) COMMENT '贷方金额合计',
    ENTRY_COUNT NUMBER(10) COMMENT '分录数量',
    VOUCHER_STATUS NUMBER(2) DEFAULT 0 COMMENT '凭证状态(0草稿1已生成2已过账3已取消)',
    SOURCE_TRANSACTION_ID NUMBER(20) COMMENT '来源事项ID',
    SOURCE_SYSTEM VARCHAR2(50) COMMENT '来源系统',
    PREPARER NUMBER(20) COMMENT '制单人',
    REVIEWER NUMBER(20) COMMENT '审核人',
    REVIEW_TIME TIMESTAMP COMMENT '审核时间',
    POSTER NUMBER(20) COMMENT '过账人',
    POST_TIME TIMESTAMP COMMENT '过账时间',
    ATTACHMENT_COUNT NUMBER(10) DEFAULT 0 COMMENT '附件数量',
    REMARK VARCHAR2(1000) COMMENT '备注',
    BOOK_ID NUMBER(20) NOT NULL COMMENT '账簿ID',
    TENANT_ID NUMBER(20) NOT NULL COMMENT '租户ID',
    IS_DELETED NUMBER(1) DEFAULT 0 COMMENT '删除标识(0否1是)',
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UPDATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
    CREATOR NUMBER(20) COMMENT '创建人',
    UPDATER NUMBER(20) COMMENT '更新人'
);

-- 添加表注释
COMMENT ON TABLE T_ACCOUNTING_VOUCHER IS '会计凭证表';

