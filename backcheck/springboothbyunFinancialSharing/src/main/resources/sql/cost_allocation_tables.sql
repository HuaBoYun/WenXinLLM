-- 创建成本分摊主表
-- 说明: 存储成本分摊的基本信息和状态
CREATE TABLE T_COST_ALLOCATION (
    -- 主键字段
    ALLOCATION_ID BIGINT PRIMARY KEY,
    ALLOCATION_NO VARCHAR(50) UNIQUE NOT NULL,

    -- 业务字段
    ALLOCATION_PERIOD VARCHAR(20) NOT NULL,               -- 分摊期间 (格式: YYYY-MM)
    SOURCE_CENTER_ID VARCHAR(20) NOT NULL,               -- 源成本中心ID
    ALLOCATION_METHOD VARCHAR(50) NOT NULL,              -- 分摊方法 (QUANTITY_BASED, AMOUNT_BASED, RATIO_BASED, HOUR_BASED)
    TOTAL_AMOUNT DECIMAL(18,2) NOT NULL,                 -- 分摊总额
    ALLOCATION_STATUS INTEGER DEFAULT 1,                 -- 分摊状态 (1:待分摊 2:分摊中 3:已分摊 4:已审核)
    ALLOCATION_DATE DATE NOT NULL,                       -- 分摊日期
    IS_GENERATE_VOUCHER INTEGER DEFAULT 0,               -- 是否生成凭证 (0:否 1:是)
    VOUCHER_ID BIGINT,                                   -- 凭证ID
    REMARK VARCHAR(500),                                 -- 备注

    -- 多租户字段
    BOOK_ID VARCHAR(20) NOT NULL,                        -- 账簿ID
    TENANT_ID VARCHAR(20) NOT NULL,                      -- 租户ID

    -- 乐观锁和软删除字段
    VERSION INTEGER DEFAULT 1,                           -- 版本号
    IS_DELETED INTEGER DEFAULT 0,                        -- 是否删除 (0:未删除 1:已删除)

    -- 审计字段
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,     -- 创建时间
    UPDATE_TIME TIMESTAMP,                               -- 更新时间
    CREATOR BIGINT,                                      -- 创建人
    UPDATER BIGINT                                       -- 更新人
);

-- 创建成本分摊明细表
-- 说明: 存储每个目标成本中心的分摊明细信息
CREATE TABLE T_COST_ALLOCATION_DETAIL (
    -- 主键字段
    DETAIL_ID BIGINT PRIMARY KEY,
    ALLOCATION_ID BIGINT NOT NULL,                       -- 关联主表ID

    -- 业务字段
    TARGET_CENTER_ID VARCHAR(20) NOT NULL,               -- 目标成本中心ID
    ALLOCATION_BASIS_VALUE DECIMAL(18,4) NOT NULL,       -- 分摊基础值
    ALLOCATION_RATIO DECIMAL(8,4) NOT NULL,              -- 分摊比例
    ALLOCATED_AMOUNT DECIMAL(18,2) NOT NULL,             -- 分摊金额
    REMARK VARCHAR(500),                                 -- 备注

    -- 多租户字段
    BOOK_ID VARCHAR(20) NOT NULL,                        -- 账簿ID
    TENANT_ID VARCHAR(20) NOT NULL,                      -- 租户ID

    -- 乐观锁和软删除字段
    VERSION INTEGER DEFAULT 1,                           -- 版本号
    IS_DELETED INTEGER DEFAULT 0,                        -- 是否删除 (0:未删除 1:已删除)

    -- 审计字段
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,     -- 创建时间
    UPDATE_TIME TIMESTAMP,                               -- 更新时间
    CREATOR BIGINT,                                      -- 创建人
    UPDATER BIGINT,                                      -- 更新人

    -- 外键约束
    FOREIGN KEY (ALLOCATION_ID) REFERENCES T_COST_ALLOCATION(ALLOCATION_ID)
);

