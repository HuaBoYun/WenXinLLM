-- 创建视图以简化查询
-- 成本分摊汇总视图（包含成本中心名称）
CREATE VIEW V_COST_ALLOCATION_SUMMARY AS
SELECT
    a.ALLOCATION_ID,
    a.ALLOCATION_NO,
    a.ALLOCATION_PERIOD,
    a.SOURCE_CENTER_ID,
    sc.CENTER_NAME as SOURCE_CENTER_NAME,
    a.ALLOCATION_METHOD,
    a.TOTAL_AMOUNT,
    a.ALLOCATION_STATUS,
    a.ALLOCATION_DATE,
    a.IS_GENERATE_VOUCHER,
    a.VOUCHER_ID,
    a.REMARK,
    a.BOOK_ID,
    a.TENANT_ID,
    a.CREATE_TIME,
    a.UPDATE_TIME,
    -- 统计信息
    d.TARGET_CENTER_COUNT,
    d.TOTAL_ALLOCATED_AMOUNT,
    -- 状态描述
    CASE a.ALLOCATION_STATUS
        WHEN 1 THEN '待分摊'
        WHEN 2 THEN '分摊中'
        WHEN 3 THEN '已分摊'
        WHEN 4 THEN '已审核'
        ELSE '未知状态'
    END as ALLOCATION_STATUS_NAME,
    -- 分摊方法描述
    CASE a.ALLOCATION_METHOD
        WHEN 'QUANTITY_BASED' THEN '数量基础'
        WHEN 'AMOUNT_BASED' THEN '金额基础'
        WHEN 'RATIO_BASED' THEN '比例基础'
        WHEN 'HOUR_BASED' THEN '工时基础'
        ELSE '未知方法'
    END as ALLOCATION_METHOD_NAME
FROM T_COST_ALLOCATION a
LEFT JOIN T_COST_CENTER sc ON a.SOURCE_CENTER_ID = sc.CENTER_ID AND sc.IS_DELETED = 0
LEFT JOIN (
    SELECT
        ALLOCATION_ID,
        COUNT(*) as TARGET_CENTER_COUNT,
        SUM(ALLOCATED_AMOUNT) as TOTAL_ALLOCATED_AMOUNT
    FROM T_COST_ALLOCATION_DETAIL
    WHERE IS_DELETED = 0
    GROUP BY ALLOCATION_ID
) d ON a.ALLOCATION_ID = d.ALLOCATION_ID
WHERE a.IS_DELETED = 0;

-- 成本分摊明细视图（包含成本中心名称）
CREATE VIEW V_COST_ALLOCATION_DETAIL AS
SELECT
    d.DETAIL_ID,
    d.ALLOCATION_ID,
    a.ALLOCATION_NO,
    a.ALLOCATION_PERIOD,
    a.SOURCE_CENTER_ID,
    sc.CENTER_NAME as SOURCE_CENTER_NAME,
    d.TARGET_CENTER_ID,
    tc.CENTER_NAME as TARGET_CENTER_NAME,
    d.ALLOCATION_BASIS_VALUE,
    d.ALLOCATION_RATIO,
    d.ALLOCATED_AMOUNT,
    d.REMARK,
    d.BOOK_ID,
    d.TENANT_ID,
    d.CREATE_TIME,
    d.UPDATE_TIME
FROM T_COST_ALLOCATION_DETAIL d
LEFT JOIN T_COST_ALLOCATION a ON d.ALLOCATION_ID = a.ALLOCATION_ID AND a.IS_DELETED = 0
LEFT JOIN T_COST_CENTER sc ON a.SOURCE_CENTER_ID = sc.CENTER_ID AND sc.IS_DELETED = 0
LEFT JOIN T_COST_CENTER tc ON d.TARGET_CENTER_ID = tc.CENTER_ID AND tc.IS_DELETED = 0
WHERE d.IS_DELETED = 0;

