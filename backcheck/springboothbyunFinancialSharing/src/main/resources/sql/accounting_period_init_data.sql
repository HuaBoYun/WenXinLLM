SELECT
    YEAR_NO as 年度,
    COUNT(*) as 期间数量,
    COUNT(CASE WHEN PERIOD_STATUS = 'OPEN' THEN 1 END) as 开启期间,
    COUNT(CASE WHEN PERIOD_STATUS = 'CLOSED' THEN 1 END) as 关闭期间,
    COUNT(CASE WHEN PERIOD_STATUS = 'CREATED' THEN 1 END) as 已创建期间,
    COUNT(CASE WHEN IS_CURRENT = 1 THEN 1 END) as 当前期间
