-- 说明：币种汇率基础信息表

-- 删除表（如果存在）
DROP TABLE IF EXISTS T_CURRENCY_RATE;

-- 创建币种汇率表
CREATE TABLE T_CURRENCY_RATE (
    RATE_ID BIGINT PRIMARY KEY,              -- 汇率ID
    CURRENCY_CODE VARCHAR(10) NOT NULL,      -- 币种编码
    CURRENCY_NAME VARCHAR(100) NOT NULL,     -- 币种名称
    RATE_TYPE INTEGER NOT NULL,              -- 汇率类型(1即期2远期3固定)
    EXCHANGE_RATE DECIMAL(20,8) NOT NULL,    -- 汇率
    RATE_DATE DATE NOT NULL,                -- 汇率日期
    IS_BASE_CURRENCY INTEGER DEFAULT 0,      -- 是否本位币(0否1是)
    IS_ENABLED INTEGER DEFAULT 1,           -- 是否启用(0否1是)
    BOOK_ID NUMBER(20) NOT NULL,            -- 账簿ID
    TENANT_ID NUMBER(20) NOT NULL,          -- 租户ID
    VERSION NUMBER(10) DEFAULT 0,           -- 版本号（乐观锁）
    IS_DELETED INTEGER DEFAULT 0,           -- 删除标识：0否 1是
    CREATE_TIME DATE DEFAULT SYSDATE,       -- 创建时间
    UPDATE_TIME DATE,                       -- 更新时间
    CREATOR NUMBER(20),                    -- 创建人
    UPDATER NUMBER(20)                     -- 更新人
);

-- 添加注释
COMMENT ON TABLE T_CURRENCY_RATE IS '币种汇率表';
COMMENT ON COLUMN T_CURRENCY_RATE.RATE_ID IS '汇率ID';
COMMENT ON COLUMN T_CURRENCY_RATE.CURRENCY_CODE IS '币种编码';
COMMENT ON COLUMN T_CURRENCY_RATE.CURRENCY_NAME IS '币种名称';
COMMENT ON COLUMN T_CURRENCY_RATE.RATE_TYPE IS '汇率类型(1即期2远期3固定)';
COMMENT ON COLUMN T_CURRENCY_RATE.EXCHANGE_RATE IS '汇率';
COMMENT ON COLUMN T_CURRENCY_RATE.RATE_DATE IS '汇率日期';
COMMENT ON COLUMN T_CURRENCY_RATE.IS_BASE_CURRENCY IS '是否本位币(0否1是)';
COMMENT ON COLUMN T_CURRENCY_RATE.IS_ENABLED IS '是否启用(0否1是)';
COMMENT ON COLUMN T_CURRENCY_RATE.BOOK_ID IS '账簿ID';
COMMENT ON COLUMN T_CURRENCY_RATE.TENANT_ID IS '租户ID';
COMMENT ON COLUMN T_CURRENCY_RATE.VERSION IS '版本号';
COMMENT ON COLUMN T_CURRENCY_RATE.IS_DELETED IS '删除标识：0否 1是';
COMMENT ON COLUMN T_CURRENCY_RATE.CREATE_TIME IS '创建时间';
COMMENT ON COLUMN T_CURRENCY_RATE.UPDATE_TIME IS '更新时间';
COMMENT ON COLUMN T_CURRENCY_RATE.CREATOR IS '创建人';
COMMENT ON COLUMN T_CURRENCY_RATE.UPDATER IS '更新人';

-- 创建索引
CREATE INDEX IDX_CURRENCY_CODE ON T_CURRENCY_RATE(CURRENCY_CODE, TENANT_ID, BOOK_ID);
CREATE INDEX IDX_RATE_DATE ON T_CURRENCY_RATE(RATE_DATE, TENANT_ID, BOOK_ID);
CREATE INDEX IDX_TENANT_BOOK ON T_CURRENCY_RATE(TENANT_ID, BOOK_ID);
CREATE INDEX IDX_IS_DELETED ON T_CURRENCY_RATE(IS_DELETED);
CREATE INDEX IDX_IS_ENABLED ON T_CURRENCY_RATE(IS_ENABLED);

