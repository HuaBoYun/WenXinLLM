CREATE INDEX IDX_COST_BUDGET_YEAR_QUARTER ON T_COST_BUDGET(BUDGET_YEAR, BUDGET_QUARTER);
CREATE INDEX IDX_COST_BUDGET_DELETED ON T_COST_BUDGET(IS_DELETED);
CREATE INDEX IDX_COST_BUDGET_BOOK_TENANT ON T_COST_BUDGET(BOOK_ID, TENANT_ID);
CREATE INDEX IDX_COST_BUDGET_STATUS ON T_COST_BUDGET(STATUS);

