-- 创建成本预算表
-- 适配达梦数据库语法
-- 表名: T_COST_BUDGET

-- 删除表（如果存在）
DROP TABLE IF EXISTS T_COST_BUDGET;

-- 创建成本预算表
CREATE TABLE T_COST_BUDGET (
    BUDGET_ID NUMBER(20) PRIMARY KEY,
    CENTER_ID NUMBER(20) NOT NULL,                    -- 成本中心ID
    BUDGET_YEAR VARCHAR2(10) NOT NULL,                -- 预算年度
    BUDGET_QUARTER VARCHAR2(2),                       -- 预算季度（1-4）
    TOTAL_BUDGET DECIMAL(20,2) DEFAULT 0,             -- 总预算金额
    ACTUAL_COST DECIMAL(20,2) DEFAULT 0,              -- 实际成本
    REMAINING_BUDGET DECIMAL(20,2) DEFAULT 0,         -- 剩余预算
    COST_CATEGORY VARCHAR2(50),                       -- 成本类别
    STATUS NUMBER(1) DEFAULT 1,                       -- 状态：1-启用，0-停用
    REMARK VARCHAR2(500),                             -- 备注
    IS_DELETED NUMBER(1) DEFAULT 0,                   -- 删除标记：0-未删除，1-已删除
    BOOK_ID VARCHAR2(50),                             -- 账簿ID
    TENANT_ID VARCHAR2(50),                           -- 租户ID
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,  -- 创建时间
    UPDATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,  -- 更新时间
    CREATOR VARCHAR2(50),                             -- 创建人
    UPDATER VARCHAR2(50)                              -- 更新人
);

