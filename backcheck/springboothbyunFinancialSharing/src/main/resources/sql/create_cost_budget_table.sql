COMMENT ON COLUMN T_COST_BUDGET.UPDATER IS '更新人';

-- 创建序列（用于自动生成ID）
CREATE SEQUENCE SEQ_COST_BUDGET_ID
INCREMENT BY 1
START WITH 1
MAXVALUE 99999999999999999999
MINVALUE 1
CACHE 20;

-- 创建触发器（自动设置ID）
CREATE OR REPLACE TRIGGER TRG_COST_BUDGET_ID
BEFORE INSERT ON T_COST_BUDGET
FOR EACH ROW
WHEN (NEW.BUDGET_ID IS NULL)
BEGIN
    SELECT SEQ_COST_BUDGET_ID.NEXTVAL INTO :NEW.BUDGET_ID FROM DUAL;
END;
/

-- 创建触发器（自动更新UPDATE_TIME）
CREATE OR REPLACE TRIGGER TRG_COST_BUDGET_UPDATE_TIME
BEFORE UPDATE ON T_COST_BUDGET
FOR EACH ROW
BEGIN
    :NEW.UPDATE_TIME := CURRENT_TIMESTAMP;
END;
/;

