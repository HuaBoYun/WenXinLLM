-- =====================================================
-- 总账管理模块数据库表结构
-- 创建日期：2024-12-08
-- 说明：创建总账管理所需的科目余额表和总账表
-- 兼容：达梦数据库、MySQL、Oracle
-- =====================================================

-- 1. 科目余额表
CREATE TABLE IF NOT EXISTS TBL_SUBJECT_BALANCE (
    BALANCE_ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    SUBJECT_ID BIGINT NOT NULL,
    SUBJECT_CODE VARCHAR(50) NOT NULL,
    SUBJECT_NAME VARCHAR(200) NOT NULL,
    ACCOUNTING_PERIOD VARCHAR(20) NOT NULL,
    BEGINNING_BALANCE DECIMAL(20,2) DEFAULT 0,
    PERIOD_DEBIT_AMOUNT DECIMAL(20,2) DEFAULT 0,
    PERIOD_CREDIT_AMOUNT DECIMAL(20,2) DEFAULT 0,
    ENDING_BALANCE DECIMAL(20,2) DEFAULT 0,
    BALANCE_DIRECTION VARCHAR(10) NOT NULL,
    BOOK_ID BIGINT NOT NULL,
    TENANT_ID BIGINT NOT NULL,
    CREATED_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_TIME TIMESTAMP,
    UNIQUE KEY UK_SUBJECT_PERIOD (SUBJECT_ID, ACCOUNTING_PERIOD, BOOK_ID, TENANT_ID)
);

-- 2. 总账表
CREATE TABLE IF NOT EXISTS TBL_GENERAL_LEDGER (
    LEDGER_ID BIGINT IDENTITY(1,1) PRIMARY KEY,
    VOUCHER_ID BIGINT NOT NULL,
    DETAIL_ID BIGINT NOT NULL,
    ACCOUNTING_DATE DATE NOT NULL,
    VOUCHER_NO VARCHAR(50) NOT NULL,
    ACCOUNT_CODE VARCHAR(50) NOT NULL,
    ACCOUNT_NAME VARCHAR(200) NOT NULL,
    SUMMARY VARCHAR(500),
    DEBIT_AMOUNT DECIMAL(20,2) DEFAULT 0,
    CREDIT_AMOUNT DECIMAL(20,2) DEFAULT 0,
    BALANCE DECIMAL(20,2) DEFAULT 0,
    VOUCHER_TYPE VARCHAR(20),
    ACCOUNTING_PERIOD VARCHAR(20) NOT NULL,
    BOOK_ID BIGINT NOT NULL,
    TENANT_ID BIGINT NOT NULL,
    CREATED_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 创建索引提高查询性能
CREATE INDEX IF NOT EXISTS IDX_SUBJECT_BALANCE_PERIOD ON TBL_SUBJECT_BALANCE(ACCOUNTING_PERIOD, BOOK_ID, TENANT_ID);
CREATE INDEX IF NOT EXISTS IDX_SUBJECT_BALANCE_SUBJECT ON TBL_SUBJECT_BALANCE(SUBJECT_CODE, BOOK_ID, TENANT_ID);
CREATE INDEX IF NOT EXISTS IDX_GENERAL_LEDGER_PERIOD ON TBL_GENERAL_LEDGER(ACCOUNTING_PERIOD, BOOK_ID, TENANT_ID);
CREATE INDEX IF NOT EXISTS IDX_GENERAL_LEDGER_ACCOUNT ON TBL_GENERAL_LEDGER(ACCOUNT_CODE, BOOK_ID, TENANT_ID);
CREATE INDEX IF NOT EXISTS IDX_GENERAL_LEDGER_DATE ON TBL_GENERAL_LEDGER(ACCOUNTING_DATE, BOOK_ID, TENANT_ID);
CREATE INDEX IF NOT EXISTS IDX_GENERAL_LEDGER_VOUCHER ON TBL_GENERAL_LEDGER(VOUCHER_NO, BOOK_ID, TENANT_ID);

