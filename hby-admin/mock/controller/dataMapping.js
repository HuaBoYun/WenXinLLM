module.exports = [
  {
    url: '/qqsk/financial/basicConfig/mapping/list',
    type: 'post',
    response(req) {
      const {
        page = 1,
        limit = 20,
        mappingName,
        sourceSystem,
        targetSystem,
      } = req.body || {}
      let filtered = [...mockList]
      if (mappingName)
        filtered = filtered.filter((i) => i.mappingName.includes(mappingName))
      if (sourceSystem)
        filtered = filtered.filter((i) => i.sourceSystem.includes(sourceSystem))
      if (targetSystem)
        filtered = filtered.filter((i) => i.targetSystem.includes(targetSystem))
      const start = (Number(page) - 1) * Number(limit)
      const tlist = filtered.slice(start, start + Number(limit))
      return {
        code: 1,
        msg: 'success',
        data: { tlist, totalRecord: filtered.length },
      }
    },
  },
]
