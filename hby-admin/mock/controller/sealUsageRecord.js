module.exports = [
  {
    url: '/qqsk/financial/basicConfig/sealUsageRecord/list',
    type: 'post',
    response(req) {
      const {
        page = 1,
        limit = 20,
        recordNumber,
        sealCode,
        sealName,
        usageType,
        usageStatus,
      } = req.body || {}
      let filtered = [...mockList]
      if (recordNumber)
        filtered = filtered.filter((i) => i.recordNumber.includes(recordNumber))
      if (sealCode)
        filtered = filtered.filter((i) => i.sealCode.includes(sealCode))
      if (sealName)
        filtered = filtered.filter((i) => i.sealName.includes(sealName))
      if (usageType)
        filtered = filtered.filter((i) => i.usageType === usageType)
      if (usageStatus)
        filtered = filtered.filter((i) => i.usageStatus === usageStatus)
      const start = (Number(page) - 1) * Number(limit)
      const tlist = filtered.slice(start, start + Number(limit))
      return {
        code: 1,
        msg: 'success',
        data: { tlist, totalRecord: filtered.length },
      }
    },
  },
]
