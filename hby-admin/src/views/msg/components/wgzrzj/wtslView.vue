    },
    mounted() {},
    methods: {
      async ymsubmit() {
        this.$refs['ruleForm'].validate(async (valid) => {
          if (valid) {
            this.$refs.resubmit.ymsubmit()
          }
        })
      },
      showEdit(
        title,
        formId,
        flowtaskinfoflowid,
        ymFromId,
        isWfqdedit,
        status
      ) {
        this.disabled = title === 'edit'
        this.fromId = formId
        this.ymFromId = ymFromId
        this.flowtaskinfoflowid = flowtaskinfoflowid
        this.fromIdcopy = formId
        this.status = status
        this.getData(formId)
        this.getFileData(formId)
      },
      async getData(row) {
        const { data } = await wtslDetail({ id: row })
        Object.assign(this.formData, data.tblYqnsWgzzWtsl)
      },
      async getFileData(row) {
        const { data } = await wtslFileList({ id: row })
        this.tableData = data.attList
      },
      save() {
        this.$refs['ruleForm'].validate(async (valid) => {
          if (valid) {
            let attIds = ''
            this.tableData.map((item) => {
              attIds += item.attid
              attIds += ','
            })
            attIds = attIds.substring(0, attIds.length - 1)
            let params = { ...this.formData }
            delete params.createtime
            delete params.creator
            const { data, code, msg } = await wtslSave({
              ...params,
              attIds,
            })
            if (code == 1) this.$message.success('保存成功')
            this.$emit('fetchData')
          }
        })
      },
      close() {
        this.formData = {
          attIds: '',
          filue: '',
          id: '',
          memo: '',
          slname: '',
          slnumber: '',
        }
        this.tableData = []
        this.dialogFormVisible = false
        this.disabled = false
        this.$bus.$emit('updateMsg', 0)
      },
      selectedCompany(node) {
        this.formData.editorgname = node.name
        this.formData.editorgid = node.id
      },
      /**
       * @description: 删除列表数据
       * @param {*} row 当前行数据
       * @return {*}
       */
      handleDelete(row) {
        this.$confirm('此操作将永久删除, 是否继续?', '提示', {
          confirmButtonText: '确定',
          cancelButtonText: '取消',
          type: 'warning',
        }).then(async () => {
          //删除对应的id
          let res = await wtslFileDelete({ attId: row.attid })
          if (res.msg === '成功') {
            this.$message({
              type: 'success',
              message: '删除成功!',
            })
            let list = this.tableData
            list = list.filter((item) => item.attid != row.attid)
            this.tableData = list
          } else {
            this.$message({
              type: 'info',
              message: '已取消删除',
            })
          }
        })
      },
